#!/usr/bin/env python3
"""Bind BOTH branches of pinned Node.search's local-params initializer."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT=Path(__file__).resolve().parents[2]
REVISION='5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE='src/router/trie-router/node.ts'

def git(checkout,*args):
    return subprocess.check_output(['git','-C',str(checkout),*args])

def artifacts(checkout):
    if git(checkout,'rev-parse','HEAD').decode().strip()!=REVISION:
        raise ValueError('Expected exact pinned Hono revision')
    if git(checkout,'status','--porcelain','--untracked-files=all').strip():
        raise ValueError('Expected clean checkout; no reset is performed')
    raw=git(checkout,'show',REVISION+':'+SOURCE)
    if (checkout/SOURCE).read_bytes()!=raw:
        raise ValueError('Working source differs from pinned Git bytes')
    lines=raw.splitlines(keepends=True)
    start,end=sum(map(len,lines[:122])),sum(map(len,lines[:123]))
    source=raw[start:end]
    digest=hashlib.sha256(source).hexdigest()
    if digest!='6b7b4f3a523c4226e9a766dfadf996c15d130b51ab5ad96d47a61cf64b4e46c2':
        raise ValueError('Expected complete exact81B source123')
    fragment=dict(firstLine=123,lastLine=123,startByte=start,endByteExclusive=end,
        sha256=digest,sourceCopy='verification/params-init/full.ts.txt')
    metadata=dict(schemaVersion=1,revision=REVISION,repository='https://github.com/honojs/hono.git',
        sourcePath=SOURCE,sourceGitBlob=git(checkout,'rev-parse',REVISION+':'+SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(raw).hexdigest(),fragments=dict(full=fragment),
        languageReference='ECMA-262, 16th edition (2025)',
        sourceBoundary='Complete original conditional initializer123, retaining BOTH empty and object-spread literal arms, identity test and private reads. No synthetic branch replacement; containing pattern loop/search reachability remain open.',
        semanticBoundary='Identity-derived branch; one fresh ordinary object; unequal arm shallow copies own enumerable DATA descriptors via CreateDataProperty rather than Set. Nonenumerable accessors and inherited properties omitted. Any legal own-string-key order gets extensional contract, not equal raw heap order or native OwnPropertyKeys adequacy. Enumerable getters/proxies/symbols/general native adequacy remain open.',
        formalCompleteSearchTheorem=None,formalNativeLanguageAdequacyTheorem=None)
    lean='-- Generated by verification/params-init/source.py; identity is externally checked.\nnamespace HonoLean.Upstream.NodeParamsInit\n\n'
    lean+='def pinnedSource : String := '+json.dumps(source.decode('ascii'))+'\n\nend HonoLean.Upstream.NodeParamsInit\n'
    return {ROOT/fragment['sourceCopy']:source,
        ROOT/'verification/params-init/source.json':(json.dumps(metadata,indent=2)+'\n').encode(),
        ROOT/'HonoLean/Upstream/NodeParamsInit/Generated.lean':lean.encode()}

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono',type=Path,required=True)
    parser.add_argument('--write',action='store_true')
    args=parser.parse_args()
    for path,contents in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(contents)
        elif not path.exists() or path.read_bytes()!=contents:
            raise SystemExit(f'Stale or changed artifact: {path.relative_to(ROOT)}')
    print('Pinned complete81B params initializer123 and both arms checked.')

if __name__=='__main__':main()
