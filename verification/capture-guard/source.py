#!/usr/bin/env python3
"""Bind the original guarded parameter-capture block to the fixed Hono source."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/router/trie-router/node.ts'


def git(checkout, *args):
    return subprocess.check_output(['git', '-C', str(checkout), *args])


def artifacts(checkout):
    if git(checkout, 'rev-parse', 'HEAD').decode().strip() != REVISION:
        raise ValueError('Expected exact pinned Hono revision')
    if git(checkout, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('Expected clean checkout; no reset is performed')
    raw = git(checkout, 'show', REVISION + ':' + SOURCE)
    if (checkout / SOURCE).read_bytes() != raw:
        raise ValueError('Working source differs from pinned Git bytes')
    lines, fragments, copies = raw.splitlines(keepends=True), {}, {}
    for name, first, last in [('full', 158, 160), ('guard', 158, 158), ('assignment', 159, 159), ('close', 160, 160)]:
        start, end = sum(map(len, lines[:first-1])), sum(map(len, lines[:last]))
        contents = raw[start:end]
        fragments[name] = dict(firstLine=first, lastLine=last, startByte=start,
            endByteExclusive=end, sha256=hashlib.sha256(contents).hexdigest(),
            sourceCopy=f'verification/capture-guard/{name}.ts.txt')
        copies[name] = contents
    if fragments['full']['sha256'] != 'beff10a225df509ff6010efcaa6271d564693b14a5f1d683d90937170d7c023b':
        raise ValueError('Expected exact source158–160')
    if copies['guard'] + copies['assignment'] + copies['close'] != copies['full']:
        raise ValueError('Exact components do not reassemble source')
    metadata = dict(schemaVersion=1, revision=REVISION, repository='https://github.com/honojs/hono.git',
        sourcePath=SOURCE, sourceGitBlob=git(checkout, 'rev-parse', REVISION + ':' + SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(raw).hexdigest(), fragments=fragments,
        languageReference='ECMA-262, 16th edition (2025)',
        sourceBoundary='Complete original Object.hasOwn guard and indexed capture assignment158–160; exact guard+assignment+close reassembly. Matcher.exec156 and enclosing if(m)/search are not included.',
        semanticBoundary='Allocated ordinary params, primitive UTF16 name and standard frozen Object.hasOwn binding. An own descriptor skips without m readiness; absent own capture derives ordinary descriptor/prototype Set, including inherited legacy setter no-op and rejection. Actual m production and complete native/frontend/realm adequacy remain open.',
        formalCompleteSearchTheorem=None, formalNativeLanguageAdequacyTheorem=None)
    lean = '-- Generated by verification/capture-guard/source.py; identity is externally checked.\nnamespace HonoLean.Upstream.NodeCaptureGuard\n\n'
    for name, constant in [('full','pinnedSource'),('guard','pinnedGuard'),('assignment','pinnedAssignment'),('close','pinnedClose')]:
        lean += 'def '+constant+' : String := '+json.dumps(copies[name].decode('ascii'))+'\n\n'
    lean += 'end HonoLean.Upstream.NodeCaptureGuard\n'
    result = {ROOT/fragments[name]['sourceCopy']:contents for name,contents in copies.items()}
    result[ROOT/'verification/capture-guard/source.json'] = (json.dumps(metadata,indent=2)+'\n').encode()
    result[ROOT/'HonoLean/Upstream/NodeCaptureGuard/Generated.lean'] = lean.encode()
    return result


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono',type=Path,required=True)
    parser.add_argument('--write',action='store_true')
    args=parser.parse_args()
    for path,contents in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(contents)
        elif not path.exists() or path.read_bytes()!=contents:
            raise SystemExit(f'Stale or changed artifact: {path.relative_to(ROOT)}')
    print('Pinned102B158–160 capture guard and exact components checked.')


if __name__=='__main__':
    main()
