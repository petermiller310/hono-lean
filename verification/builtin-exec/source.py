#!/usr/bin/env python3
"""Bind original156/157 for the closed builtin-RegExp invocation slice."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/router/trie-router/node.ts'
SPANS = {
    'full': (156, 'dd13b5b1aed7d6f0a70808b80bcd633f572ea02596a1368573de50a48ac8b625'),
    'guard-header': (157, '042e769ef1bf1960c8afe661fb6685043688d65289af9f4e6611beaa86d4336f'),
}


def git(checkout, *args):
    return subprocess.check_output(['git', '-C', str(checkout), *args])


def artifacts(checkout):
    if git(checkout, 'rev-parse', 'HEAD').decode().strip() != REVISION:
        raise ValueError('Expected exact pinned Hono revision')
    if git(checkout, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('Expected clean checkout; no reset is performed')
    raw = git(checkout, 'show', REVISION + ':' + SOURCE)
    if (checkout / SOURCE).read_bytes() != raw:
        raise ValueError('Working source differs from pinned Git bytes')
    lines = raw.splitlines(keepends=True)
    fragments, contents = {}, {}
    for name, (line, expected) in SPANS.items():
        start = sum(map(len, lines[:line-1]))
        source = lines[line-1]
        digest = hashlib.sha256(source).hexdigest()
        if digest != expected:
            raise ValueError('Expected original pinned ' + name + ' fragment')
        copy = 'verification/builtin-exec/' + name + '.ts.txt'
        fragments[name] = dict(firstLine=line, lastLine=line, startByte=start,
            endByteExclusive=start+len(source), sha256=digest, sourceCopy=copy)
        contents[ROOT / copy] = source
    metadata = dict(schemaVersion=1, revision=REVISION, repository='https://github.com/honojs/hono.git',
        sourcePath=SOURCE, sourceGitBlob=git(checkout, 'rev-parse', REVISION + ':' + SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(raw).hexdigest(), fragments=fragments,
        languageReference='ECMA-262, 16th edition (2025)',
        sourceBoundary='Complete actual51B156 const declaration; separate original21B157 header identifies only actual test syntax. No invented if body is substituted for upstream code.',
        semanticBoundary='Saved current callable identity selects a closed ordinary or builtin-RegExp target. Branded receiver has checked parsed/compiled range-plus program; operational matcher derives null/freshresult plus metadata with actual numeric nonglobal lastIndex frames. No match result oracle or exec-name dispatch. Constructor/getPattern/cache/tuple provenance, full regex grammar/flags, outer reachability and native adequacy remain open.',
        formalBuiltinRegExpExecTheorem=None, formalCompleteSearchTheorem=None,
        formalNativeLanguageAdequacyTheorem=None)
    contents[ROOT / 'verification/builtin-exec/source.json'] = (json.dumps(metadata, indent=2) + '\n').encode()
    lean = '-- Generated by verification/builtin-exec/source.py; identity is externally checked.\nnamespace HonoLean.Upstream.NodeRegExpExec\n\n'
    for name, constant in [('full', 'pinnedSource'), ('guard-header', 'pinnedGuardHeader')]:
        lean += 'def ' + constant + ' : String := ' + json.dumps(contents[ROOT / fragments[name]['sourceCopy']].decode('ascii')) + '\n\n'
    lean += 'end HonoLean.Upstream.NodeRegExpExec\n'
    contents[ROOT / 'HonoLean/Upstream/NodeRegExpExec/Generated.lean'] = lean.encode()
    return contents


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for path, contents in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(contents)
        elif not path.exists() or path.read_bytes() != contents:
            raise SystemExit(f'Stale or changed artifact: {path.relative_to(ROOT)}')
    print('Pinned actual51B156 directcall and separate21B157 test header checked.')


if __name__ == '__main__':
    main()
