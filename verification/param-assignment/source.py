#!/usr/bin/env python3
"""Check exact pinned assignment bytes and their containing method context.

Line selection is deliberately tied to one immutable source revision. It is an
external identity tool, not a TypeScript parser; Lean parses the selected bytes.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/router/trie-router/node.ts'


def git(checkout, *arguments):
    return subprocess.check_output(['git', '-C', str(checkout), *arguments])


def span(contents, first_line, last_line):
    lines = contents.splitlines(keepends=True)
    if len(lines) < last_line:
        raise ValueError('Pinned line span is outside source')
    start = sum(map(len, lines[:first_line - 1]))
    end = sum(map(len, lines[:last_line]))
    return start, end, contents[start:end]


def artifacts(checkout):
    actual = git(checkout, 'rev-parse', 'HEAD').decode().strip()
    if actual != REVISION:
        raise ValueError(f'Expected pinned revision {REVISION}, got {actual}')
    if git(checkout, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('Expected a clean pinned Hono checkout; no reset is performed')
    contents = git(checkout, 'show', REVISION + ':' + SOURCE)
    if (checkout / SOURCE).read_bytes() != contents:
        raise ValueError('Working source bytes differ from the pinned Git blob')
    start, end, assignment = span(contents, 79, 80)
    context_start, context_end, context = span(contents, 64, 84)
    metadata = dict(schemaVersion=1, repository='https://github.com/honojs/hono.git',
        revision=REVISION, sourcePath=SOURCE,
        sourceGitBlob=git(checkout, 'rev-parse', REVISION + ':' + SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(contents).hexdigest(),
        fragmentKind='assignment statement', firstLine=79, lastLine=80,
        startByte=start, endByteExclusive=end,
        fragmentSha256=hashlib.sha256(assignment).hexdigest(),
        whitespacePolicy='Exact source indentation and trailing LF are retained.',
        containingMethod=dict(name='Node.#pushHandlerSets', firstLine=64, lastLine=84,
            startByte=context_start, endByteExclusive=context_end,
            sha256=hashlib.sha256(context).hexdigest(), source=context.decode('ascii'),
            verificationStatus='provenance context only; surrounding method is not parsed or verified'),
        languageReference='ECMA-262 16th edition (2025)',
        sourceSubset='Generic property assignment, optional computed access, logical AND/NOT, conditional and nullish coalescing',
        linkage='External Git/line-span/embedding identity check plus kernel-checked generic fragment parsing; no whole-Node trace or complete TypeScript frontend claim',
        formalUpstreamCounterexampleTheorem=None)
    lean = ('-- Generated by verification/param-assignment/source.py; source identity is externally checked.\n'
            'import HonoLean.Upstream.SourceSubset.Syntax\n\n'
            'namespace HonoLean.Upstream.NodeParamAssignment\n\n'
            'def pinnedSource : String := ' + json.dumps(assignment.decode('ascii')) + '\n\n'
            'end HonoLean.Upstream.NodeParamAssignment\n')
    return {ROOT / 'verification/param-assignment/assignment.ts.txt': assignment,
            ROOT / 'verification/param-assignment/source.json': (json.dumps(metadata, indent=2) + '\n').encode(),
            ROOT / 'HonoLean/Upstream/NodeParamAssignment/Generated.lean': lean.encode()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for path, data in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        elif not path.exists() or path.read_bytes() != data:
            raise SystemExit(f'Stale or changed source artifact: {path.relative_to(ROOT)}')
    print('Pinned assignment lines79–80 and containing method context checked.')


if __name__ == '__main__':
    main()
