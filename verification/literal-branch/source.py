#!/usr/bin/env python3
"""Bind the complete literal-child declaration and branch, Node.search106–119."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/router/trie-router/node.ts'


def git(checkout, *args):
    return subprocess.check_output(['git', '-C', str(checkout), *args])


def artifacts(checkout):
    if git(checkout, 'rev-parse', 'HEAD').decode().strip() != REVISION:
        raise ValueError('Expected exact pinned Hono revision')
    if git(checkout, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('Expected clean pinned checkout; no reset is performed')
    raw = git(checkout, 'show', REVISION + ':' + SOURCE)
    if (checkout / SOURCE).read_bytes() != raw:
        raise ValueError('Working source bytes differ from pinned Git blob')
    lines = raw.splitlines(keepends=True)
    start = sum(map(len, lines[:105]))
    end = sum(map(len, lines[:119]))
    fragment = raw[start:end]
    metadata = dict(schemaVersion=1, revision=REVISION,
        repository='https://github.com/honojs/hono.git', sourcePath=SOURCE,
        sourceGitBlob=git(checkout, 'rev-parse', REVISION + ':' + SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(raw).hexdigest(),
        fragment=dict(firstLine=106, lastLine=119, startByte=start,
            endByteExclusive=end, sha256=hashlib.sha256(fragment).hexdigest(),
            whitespacePolicy='Exact indentation and trailing LF retained'),
        sourceSubset='Fresh lexical declaration; nested if/else; private DATA propagation; private helper calls; dense array push.',
        controlFlowBoundary='The source node selection105 and isLast derivation101 are entry premises. The declaration remains in its enclosing for-j scope. Outer search loops, path reachability, nonliteral branches and complete native-language adequacy remain open.',
        aliasBoundary='The optional wildcard call precedes the direct call. Collector entries retain live handler references; a later reset of a shared handler affects earlier aliases.',
        formalCompleteSearchTheorem=None, formalNativeActivationTheorem=None)
    lean = ('-- Generated by verification/literal-branch/source.py; source identity is externally checked.\n'
            'namespace HonoLean.Upstream.NodeLiteralBranch\n\n'
            'def pinnedSource : String := ' + json.dumps(fragment.decode('ascii')) + '\n\n'
            'end HonoLean.Upstream.NodeLiteralBranch\n')
    return {ROOT/'verification/literal-branch/source.json': (json.dumps(metadata, indent=2)+'\n').encode(),
        ROOT/'verification/literal-branch/source.ts.txt': fragment,
        ROOT/'HonoLean/Upstream/NodeLiteralBranch/Generated.lean': lean.encode()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for path, data in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        elif not path.exists() or path.read_bytes() != data:
            raise SystemExit(f'Stale or changed source artifact: {path.relative_to(ROOT)}')
    print('Pinned literal-child source106–119 and Lean embedding checked.')


if __name__ == '__main__':
    main()
