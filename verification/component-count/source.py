#!/usr/bin/env python3
"""Pin Hono's regexp count line and contiguous count-to-scheduling fragment."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/router/trie-router/node.ts'


def git(checkout, *args):
    return subprocess.check_output(['git', '-C', str(checkout), *args])


def artifacts(checkout):
    if git(checkout, 'rev-parse', 'HEAD').decode().strip() != REVISION:
        raise ValueError('Expected the exact pinned Hono revision')
    if git(checkout, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('Expected a clean pinned checkout; no reset is performed')
    raw = git(checkout, 'show', REVISION + ':' + SOURCE)
    if (checkout / SOURCE).read_bytes() != raw:
        raise ValueError('Working source differs from pinned Git bytes')
    lines = raw.splitlines(keepends=True)
    fragments = {}
    for name, first, last in [('count', 176, 176), ('full', 176, 178)]:
        start, end = sum(map(len, lines[:first - 1])), sum(map(len, lines[:last]))
        data = raw[start:end]
        fragments[name] = dict(firstLine=first, lastLine=last, startByte=start,
                               endByteExclusive=end, sha256=hashlib.sha256(data).hexdigest(),
                               sourceCopy=f'verification/component-count/{name}.ts.txt')
    count = raw[fragments['count']['startByte']:fragments['count']['endByteExclusive']]
    full = raw[fragments['full']['startByte']:fragments['full']['endByteExclusive']]
    if hashlib.sha256(count).hexdigest() != '8f93b148e6dc2f2cf67003adc4e5791a8c5c7132dcab0fd7c566599201ed9c54':
        raise ValueError('Expected exact count-producing line176')
    prior = json.loads((ROOT / 'verification/queue-schedule/source.json').read_text())
    span = prior['fragment']
    schedule = (ROOT / span['sourceCopy']).read_bytes()
    if (prior['revision'], prior['sourcePath'], prior['sourceSha256']) != (
            REVISION, SOURCE, hashlib.sha256(raw).hexdigest()):
        raise ValueError('Scheduling dependency source identity is stale')
    if (span['firstLine'], span['lastLine'], span['startByte'], span['endByteExclusive'], span['sha256']) != (
            177, 178, fragments['count']['endByteExclusive'], fragments['full']['endByteExclusive'],
            hashlib.sha256(schedule).hexdigest()):
        raise ValueError('Scheduling dependency span is stale')
    if count + schedule != full:
        raise ValueError('Count and scheduling do not reassemble the contiguous source')
    metadata = dict(schemaVersion=1, revision=REVISION, repository='https://github.com/honojs/hono.git',
        sourcePath=SOURCE, sourceGitBlob=git(checkout, 'rev-parse', REVISION + ':' + SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(raw).hexdigest(), fragments=fragments,
        scheduleDependency=dict(sourceMetadata='verification/queue-schedule/source.json', **span),
        languageReference='ECMA-262, 16th edition (2025)',
        parserBoundary='Separate original global single-unit RegExp literal/match/optional-length/nullish AST; prior source grammar and old Value/Expr/State ABI unchanged. Full191B reassembles count70B plus existing scheduling121B.',
        semanticBoundary='Projected unit RegExp cells plus indexed array store. A tracked global accumulator is allocated even if resultnull; per-exec internal arrays/other native RegExp state and total native allocation counts are not represented. Exact count/index facts derive from initial UTF16 input, not supplied output. Earlier matcher.exec/count input origin,for-in,params175,fullbody/native language adequacy remain open.',
        formalCompleteBodyTheorem=None, formalCompleteSearchTheorem=None, formalNativeLanguageAdequacyTheorem=None)
    lean = ('-- Generated by verification/component-count/source.py; identity is externally checked.\n'
            'namespace HonoLean.Upstream.NodeComponentCount\n\n'
            'def pinnedSource : String := ' + json.dumps(count.decode('ascii')) + '\n\n'
            'def pinnedFullSource : String := ' + json.dumps(full.decode('ascii')) + '\n\n'
            'end HonoLean.Upstream.NodeComponentCount\n')
    return {ROOT / 'verification/component-count/count.ts.txt': count,
            ROOT / 'verification/component-count/full.ts.txt': full,
            ROOT / 'verification/component-count/source.json': (json.dumps(metadata, indent=2) + '\n').encode(),
            ROOT / 'HonoLean/Upstream/NodeComponentCount/Generated.lean': lean.encode()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for path, contents in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(contents)
        elif not path.exists() or path.read_bytes() != contents:
            raise SystemExit(f'Stale or changed artifact: {path.relative_to(ROOT)}')
    print('Pinned count176 and contiguous176–178 reassembly checked.')


if __name__ == '__main__':
    main()
