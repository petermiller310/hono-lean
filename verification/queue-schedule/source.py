#!/usr/bin/env python3
"""Check pinned sparse queue scheduling and its existing consumer artifact."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/router/trie-router/node.ts'


def git(checkout, *arguments):
    return subprocess.check_output(['git', '-C', str(checkout), *arguments])


def artifacts(checkout):
    if git(checkout, 'rev-parse', 'HEAD').decode().strip() != REVISION:
        raise ValueError('Expected the exact pinned Hono revision')
    if git(checkout, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('Expected a clean pinned checkout; no reset is performed')
    contents = git(checkout, 'show', REVISION + ':' + SOURCE)
    if (checkout / SOURCE).read_bytes() != contents:
        raise ValueError('Working source differs from the pinned Git blob')
    lines = contents.splitlines(keepends=True)
    start, end = sum(map(len, lines[:176])), sum(map(len, lines[:178]))
    fragment = contents[start:end]
    expected = (b'                const targetCurNodes = (curNodesQueue[componentCount] ||= [])\n'
                b'                targetCurNodes.push(child)\n')
    if fragment != expected:
        raise ValueError('The selected lines are not the pinned scheduling statements')
    consumer = json.loads((ROOT / 'verification/queue-advance/source.json').read_text())
    consumer_source = (ROOT / 'verification/queue-advance/source.ts.txt').read_bytes()
    span = consumer['fragment']
    cstart, cend = sum(map(len, lines[:208])), sum(map(len, lines[:210]))
    if (consumer['revision'], consumer['sourcePath'], consumer['sourceSha256']) != (
            REVISION, SOURCE, hashlib.sha256(contents).hexdigest()):
        raise ValueError('Consumer source identity is stale')
    if (span['firstLine'], span['lastLine'], span['startByte'], span['endByteExclusive'], span['sha256']) != (
            209, 210, cstart, cend, hashlib.sha256(contents[cstart:cend]).hexdigest()):
        raise ValueError('Consumer source span is stale')
    if consumer_source != contents[cstart:cend]:
        raise ValueError('Consumer source copy differs from the pinned source')
    metadata = dict(
        schemaVersion=1, repository='https://github.com/honojs/hono.git',
        revision=REVISION, sourcePath=SOURCE,
        sourceGitBlob=git(checkout, 'rev-parse', REVISION + ':' + SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(contents).hexdigest(),
        fragment=dict(firstLine=177, lastLine=178, startByte=start,
                      endByteExclusive=end, sha256=hashlib.sha256(fragment).hexdigest(),
                      sourceCopy='verification/queue-schedule/source.ts.txt'),
        consumer=dict(sourceMetadata='verification/queue-advance/source.json', **span),
        languageReference='ECMA-262 16th edition (2025)',
        parserBoundary='Separate original logical-assignment initializer AST and indexed sequence entry; shared lexer adds only adjacent ||= maximal munch. Older Expr/Stmt/State/AssignmentReference types and parser admission remain unchanged.',
        semanticBoundary='Actual sparse own-index presence and length, numeric array-index specialization, short-circuit RHS allocation and saved-reference write, then current target push including aliases. Hole erasure is read-value observation only; no own-presence equality, general key coercion, inherited/accessor/proxy/species/native adequacy or preceding regexp/count/for-in/full-body claim.',
        formalCompleteLoopTheorem=None, formalCompleteSearchTheorem=None)
    lean = ('-- Generated by verification/queue-schedule/source.py; source identity is externally checked.\n'
            'namespace HonoLean.Upstream.NodeQueueSchedule\n\n'
            'def pinnedSource : String := ' + json.dumps(fragment.decode('ascii')) + '\n\n'
            'end HonoLean.Upstream.NodeQueueSchedule\n')
    return {
        ROOT / 'verification/queue-schedule/source.ts.txt': fragment,
        ROOT / 'verification/queue-schedule/source.json': (json.dumps(metadata, indent=2) + '\n').encode(),
        ROOT / 'HonoLean/Upstream/NodeQueueSchedule/Generated.lean': lean.encode(),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for path, data in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        elif not path.exists() or path.read_bytes() != data:
            raise SystemExit(f'Stale or changed artifact: {path.relative_to(ROOT)}')
    print('Pinned scheduling177–178 and consumer209–210 identities checked.')


if __name__ == '__main__':
    main()
