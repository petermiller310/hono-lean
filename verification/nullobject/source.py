#!/usr/bin/env python3
"""External identity/embedding check for the entire pinned router/utils.ts."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/router/utils.ts'

def git(checkout, *arguments):
    return subprocess.check_output(['git', '-C', str(checkout), *arguments])

def artifacts(checkout):
    actual = git(checkout, 'rev-parse', 'HEAD').decode().strip()
    if actual != REVISION:
        raise ValueError(f'Expected pinned revision {REVISION}, got {actual}')
    if git(checkout, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('Expected a clean pinned Hono checkout; no reset is performed')
    contents = git(checkout, 'show', REVISION + ':' + SOURCE)
    if (checkout/SOURCE).read_bytes() != contents:
        raise ValueError('Working source bytes differ from the pinned Git blob')
    body = contents.decode('ascii')
    metadata = dict(schemaVersion=1, repository='https://github.com/honojs/hono.git',
        revision=REVISION, sourcePath=SOURCE,
        sourceGitBlob=git(checkout, 'rev-parse', REVISION + ':' + SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(contents).hexdigest(),
        functionName='createNullObject', startByte=0, endByteExclusive=len(contents),
        functionSha256=hashlib.sha256(contents).hexdigest(), entireModuleEmbedded=True,
        languageReference='ECMA-262 16th edition (2025)',
        sourceSubset='ASCII zero-parameter expression-bodied declaration, ambient Object binding, method call and null literal',
        linkage='External Git/whole-file embedding checker plus kernel-checked Lean syntax; standard Object binding/dispatch and object-model adequacy remain explicit interpretation boundaries')
    lean = ('-- Generated by verification/nullobject/source.py; source identity is externally checked.\n'
            'import HonoLean.Upstream.SourceSubset.Syntax\n\n'
            'namespace HonoLean.Upstream.CreateNullObject\n\n'
            'def pinnedSource : String := ' + json.dumps(body) + '\n\n'
            'end HonoLean.Upstream.CreateNullObject\n')
    return {ROOT/'verification/nullobject/createNullObject.ts.txt': contents,
            ROOT/'verification/nullobject/source.json': (json.dumps(metadata, indent=2)+'\n').encode(),
            ROOT/'HonoLean/Upstream/CreateNullObject/Generated.lean': lean.encode()}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono', type=Path, required=True)
    parser.add_argument('--write', action='store_true', help='Regenerate the three source identity artifacts')
    args = parser.parse_args()
    for path, data in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        elif not path.exists() or path.read_bytes() != data:
            raise SystemExit(f'Stale or changed source artifact: {path.relative_to(ROOT)}')
    print('Pinned entire module and exact embedded bytes checked.')

if __name__ == '__main__':
    main()
