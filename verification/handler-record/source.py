#!/usr/bin/env python3
"""Bind the actual Node.insert push argument object to its Lean embedding.

This selects only the full object expression, not the private receiver/call,
surrounding insertion traversal, or later storage/selection/transport.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/router/trie-router/node.ts'


def git(checkout, *arguments):
    return subprocess.check_output(['git', '-C', str(checkout), *arguments])


def span(contents, first, last):
    lines = contents.splitlines(keepends=True)
    start = sum(map(len, lines[:first - 1]))
    end = sum(map(len, lines[:last]))
    return start, end, contents[start:end]


def artifacts(checkout):
    actual = git(checkout, 'rev-parse', 'HEAD').decode().strip()
    if actual != REVISION:
        raise ValueError(f'Expected pinned revision {REVISION}, got {actual}')
    if git(checkout, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('Expected clean pinned Hono checkout; no reset is performed')
    contents = git(checkout, 'show', REVISION + ':' + SOURCE)
    if (checkout / SOURCE).read_bytes() != contents:
        raise ValueError('Working source bytes differ from pinned Git blob')
    first_start, _, first = span(contents, 55, 55)
    last_start, _, last = span(contents, 61, 61)
    start = first_start + first.index(b'{')
    end = last_start + last.index(b'}') + 1
    expression = contents[start:end]
    context_start, context_end, context = span(contents, 28, 62)
    metadata = dict(schemaVersion=1, repository='https://github.com/honojs/hono.git',
        revision=REVISION, sourcePath=SOURCE,
        sourceGitBlob=git(checkout, 'rev-parse', REVISION + ':' + SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(contents).hexdigest(),
        fragment=dict(firstLine=55, lastLine=61, startByte=start, endByteExclusive=end,
            sha256=hashlib.sha256(expression).hexdigest(),
            whitespacePolicy='Exact object-expression bytes, including internal indentation/newlines/trailing comma; excludes private receiver/push call and following LF'),
        containingMethod=dict(name='Node.insert', firstLine=28, lastLine=62,
            startByte=context_start, endByteExclusive=context_end,
            sha256=hashlib.sha256(context).hexdigest(), source=context.decode('ascii'),
            verificationStatus='Provenance context only; insertion traversal/private push/storage are not parsed'),
        sourceSubset='Ordinary object literals; computed primitive-string key; shorthand/static data fields; array spread; prefix identifier increment',
        nativeBoundary='Standard Object.prototype/Set iterator, primitive string method and keys, exact safe-integer increment, legal sizes/resources and valid identities; full frontend/native adequacy open',
        formalInsertTraversalTheorem=None, formalPrivateMethodsPushTheorem=None)
    lean = ('-- Generated by verification/handler-record/source.py; source identity is externally checked.\n'
            'import HonoLean.Upstream.SourceSubset.Syntax\n\n'
            'namespace HonoLean.Upstream.HandlerRecord\n\n'
            'def pinnedSource : String := ' + json.dumps(expression.decode('ascii')) + '\n\n'
            'end HonoLean.Upstream.HandlerRecord\n')
    return {
        ROOT / 'verification/handler-record/source.json': (json.dumps(metadata, indent=2) + '\n').encode(),
        ROOT / 'verification/handler-record/source.ts.txt': expression,
        ROOT / 'HonoLean/Upstream/HandlerRecord/Generated.lean': lean.encode()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for path, data in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        elif not path.exists() or path.read_bytes() != data:
            raise SystemExit(f'Stale or changed source artifact: {path.relative_to(ROOT)}')
    print('Pinned full handler-record object argument and insertion context checked.')


if __name__ == '__main__':
    main()
