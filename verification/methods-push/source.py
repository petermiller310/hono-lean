#!/usr/bin/env python3
"""Bind the complete actual Node.insert private methods push expression.

The containing method is provenance only. Neither constructor/field
initialization nor insertion traversal/event production is translated here.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/router/trie-router/node.ts'


def git(checkout, *arguments):
    return subprocess.check_output(['git', '-C', str(checkout), *arguments])


def span(contents, first, last):
    lines = contents.splitlines(keepends=True)
    start = sum(map(len, lines[:first - 1]))
    end = sum(map(len, lines[:last]))
    return start, end, contents[start:end]


def artifacts(checkout):
    actual = git(checkout, 'rev-parse', 'HEAD').decode().strip()
    if actual != REVISION:
        raise ValueError(f'Expected pinned revision {REVISION}, got {actual}')
    if git(checkout, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('Expected clean pinned Hono checkout; no reset is performed')
    contents = git(checkout, 'show', REVISION + ':' + SOURCE)
    if (checkout / SOURCE).read_bytes() != contents:
        raise ValueError('Working source bytes differ from pinned Git blob')
    start, end, expression = span(contents, 55, 61)
    context_start, context_end, context = span(contents, 28, 62)
    metadata = dict(schemaVersion=1, repository='https://github.com/honojs/hono.git',
        revision=REVISION, sourcePath=SOURCE,
        sourceGitBlob=git(checkout, 'rev-parse', REVISION + ':' + SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(contents).hexdigest(),
        fragment=dict(firstLine=55, lastLine=61, startByte=start, endByteExclusive=end,
            sha256=hashlib.sha256(expression).hexdigest(),
            whitespacePolicy='Exact complete private receiver/member/push call, indentation, newlines and trailing LF retained'),
        containingMethod=dict(name='Node.insert', firstLine=28, lastLine=62,
            startByte=context_start, endByteExclusive=context_end,
            sha256=hashlib.sha256(context).hexdigest(), source=context.decode('ascii'),
            verificationStatus='Provenance only; constructor/field initialization and insertion traversal are not parsed'),
        sourceSubset='Lexically branded private property; prepared standard array push call before argument; complete handler-record object argument',
        formalPrivateMethodsPushTheorem='HonoLean.Upstream.NodeMethodsPush.parsed_source_correct',
        theoremBoundary='Conditional theorem in the declared source model; native/frontend/engine adequacy and actual entry reachability remain open',
        formalInsertTraversalTheorem=None)
    lean = ('-- Generated by verification/methods-push/source.py; source identity is externally checked.\n'
            'import HonoLean.Upstream.SourceSubset.Syntax\n\n'
            'namespace HonoLean.Upstream.NodeMethodsPush\n\n'
            'def pinnedSource : String := ' + json.dumps(expression.decode('ascii')) + '\n\n'
            'end HonoLean.Upstream.NodeMethodsPush\n')
    return {
        ROOT / 'verification/methods-push/source.json': (json.dumps(metadata, indent=2) + '\n').encode(),
        ROOT / 'verification/methods-push/source.ts.txt': expression,
        ROOT / 'HonoLean/Upstream/NodeMethodsPush/Generated.lean': lean.encode()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for path, data in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        elif not path.exists() or path.read_bytes() != data:
            raise SystemExit(f'Stale or changed source artifact: {path.relative_to(ROOT)}')
    print('Pinned complete private methods push expression and insertion context checked.')


if __name__ == '__main__':
    main()
