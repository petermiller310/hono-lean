#!/usr/bin/env python3
"""Bind three separate Node.search setup activations, not omitted loop headers."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/router/trie-router/node.ts'
WINDOWS = [('search', 'Search', 96, 97), ('iteration', 'Iteration', 100, 102),
           ('entry', 'Entry', 105, 119)]


def git(checkout, *args):
    return subprocess.check_output(['git', '-C', str(checkout), *args])


def artifacts(checkout):
    if git(checkout, 'rev-parse', 'HEAD').decode().strip() != REVISION:
        raise ValueError('Expected exact pinned Hono revision')
    if git(checkout, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('Expected clean pinned checkout; no reset is performed')
    raw = git(checkout, 'show', REVISION + ':' + SOURCE)
    if (checkout / SOURCE).read_bytes() != raw:
        raise ValueError('Working source bytes differ from pinned Git blob')
    lines = raw.splitlines(keepends=True)
    fragments = {}
    outputs = {}
    lean = ('-- Generated by verification/iteration-setup/source.py; source identity is externally checked.\n'
            'namespace HonoLean.Upstream.NodeIterationSetup\n\n')
    for name, lean_name, first, last in WINDOWS:
        start = sum(map(len, lines[:first-1]))
        end = sum(map(len, lines[:last]))
        fragment = raw[start:end]
        fragments[name] = dict(firstLine=first, lastLine=last, startByte=start,
            endByteExclusive=end, sha256=hashlib.sha256(fragment).hexdigest(),
            whitespacePolicy='Exact indentation and trailing LF retained')
        outputs[ROOT/f'verification/iteration-setup/{name}.ts.txt'] = fragment
        lean += f'def pinned{lean_name}Source : String := ' + json.dumps(fragment.decode('ascii')) + '\n\n'
    lean += 'end HonoLean.Upstream.NodeIterationSetup\n'
    metadata = dict(schemaVersion=1, revision=REVISION,
        repository='https://github.com/honojs/hono.git', sourcePath=SOURCE,
        sourceGitBlob=git(checkout, 'rev-parse', REVISION + ':' + SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(raw).hexdigest(), fragments=fragments,
        sourceSubset='Dense array length/index reads, subtraction/equality, typed lexical declarations, fresh empty array, and complete literal-child branch.',
        activationBoundary='The three windows execute separately. Numeric i and j are supplied across omitted loop headers99/104. No contiguous100-to105 block, loop-header production or full loop reachability theorem is claimed.',
        openBoundary='splitPath production, saved for-header lengths and conditions, interleaved pattern branches, queue progression, native language/heap adequacy and complete search remain open.',
        formalCompleteSearchTheorem=None, formalLoopReachabilityTheorem=None)
    outputs[ROOT/'verification/iteration-setup/source.json'] = (json.dumps(metadata, indent=2)+'\n').encode()
    outputs[ROOT/'HonoLean/Upstream/NodeIterationSetup/Generated.lean'] = lean.encode()
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for path, data in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        elif not path.exists() or path.read_bytes() != data:
            raise SystemExit(f'Stale or changed source artifact: {path.relative_to(ROOT)}')
    print('Pinned separate setup windows96–97/100–102/105–119 checked.')


if __name__ == '__main__':
    main()
