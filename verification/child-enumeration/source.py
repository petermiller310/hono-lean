#!/usr/bin/env python3
"""Bind the complete pinned child-enumeration loop to exact source artifacts."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/router/trie-router/node.ts'


def git(checkout, *args):
    return subprocess.check_output(['git', '-C', str(checkout), *args])


def artifacts(checkout):
    if git(checkout, 'rev-parse', 'HEAD').decode().strip() != REVISION:
        raise ValueError('Expected exact pinned Hono revision')
    if git(checkout, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('Expected a clean pinned checkout; no reset is performed')
    raw = git(checkout, 'show', REVISION + ':' + SOURCE)
    if (checkout / SOURCE).read_bytes() != raw:
        raise ValueError('Working source differs from pinned Git bytes')
    lines = raw.splitlines(keepends=True)
    fragments, copies = {}, {}
    for name, first, last in [('full', 174, 180), ('prefix', 174, 175), ('suffix', 179, 180)]:
        start, end = sum(map(len, lines[:first - 1])), sum(map(len, lines[:last]))
        data = raw[start:end]
        fragments[name] = dict(firstLine=first, lastLine=last, startByte=start,
            endByteExclusive=end, sha256=hashlib.sha256(data).hexdigest(),
            sourceCopy=f'verification/child-enumeration/{name}.ts.txt')
        copies[name] = data
    if fragments['full']['sha256'] != 'fce614b83a4e70c4b00d6f4e8e609d20109770daf866b281b2677862be5168c2':
        raise ValueError('Expected exact complete child-enumeration loop174–180')
    prior = json.loads((ROOT / 'verification/component-count/source.json').read_text())
    span = prior['fragments']['full']
    middle = (ROOT / span['sourceCopy']).read_bytes()
    if (prior['revision'], prior['sourcePath'], prior['sourceSha256']) != (
            REVISION, SOURCE, hashlib.sha256(raw).hexdigest()):
        raise ValueError('Count/scheduling dependency identity is stale')
    if (span['startByte'], span['endByteExclusive'], span['sha256']) != (
            fragments['prefix']['endByteExclusive'], fragments['suffix']['startByte'],
            hashlib.sha256(middle).hexdigest()):
        raise ValueError('Count/scheduling dependency span is stale')
    if copies['prefix'] + middle + copies['suffix'] != copies['full']:
        raise ValueError('Components do not reassemble the complete source loop')
    metadata = dict(schemaVersion=1, revision=REVISION,
        repository='https://github.com/honojs/hono.git', sourcePath=SOURCE,
        sourceGitBlob=git(checkout, 'rev-parse', REVISION + ':' + SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(raw).hexdigest(), fragments=fragments,
        countScheduleDependency=dict(sourceMetadata='verification/component-count/source.json', **span),
        languageReference='ECMA-262, 16th edition (2025)',
        sourceBoundary='Complete original for-in/private write/count/scheduling/break text. Middle is the existing checked191B source. Containing search/class and earlier matcher.exec are not included.',
        semanticBoundary='Explicit ordinary null-prototype own-string descriptor enumeration and key-insensitive body interpretation, private branded DATA write, authoritative sparse arrays and projected regexp store. No supplied enumeration outcome/count/future readiness; full frontend/native/whole-search adequacy remains open.',
        formalCompleteSearchTheorem=None, formalNativeLanguageAdequacyTheorem=None)
    lean = '-- Generated by verification/child-enumeration/source.py; identity is externally checked.\nnamespace HonoLean.Upstream.NodeChildEnumeration\n\n'
    for name, constant in [('full', 'pinnedSource'), ('prefix', 'pinnedPrefix'), ('suffix', 'pinnedSuffix')]:
        lean += 'def ' + constant + ' : String := ' + json.dumps(copies[name].decode('ascii')) + '\n\n'
    lean += 'end HonoLean.Upstream.NodeChildEnumeration\n'
    result = {ROOT / fragments[name]['sourceCopy']: contents for name, contents in copies.items()}
    result[ROOT / 'verification/child-enumeration/source.json'] = (json.dumps(metadata, indent=2) + '\n').encode()
    result[ROOT / 'HonoLean/Upstream/NodeChildEnumeration/Generated.lean'] = lean.encode()
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for path, contents in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(contents)
        elif not path.exists() or path.read_bytes() != contents:
            raise SystemExit(f'Stale or changed artifact: {path.relative_to(ROOT)}')
    print('Pinned complete174–180 loop and88+191+38 byte reassembly checked.')


if __name__ == '__main__':
    main()
