#!/usr/bin/env python3
"""Bind four exact Node.search private-data write entries.

The surrounding search method is provenance. In particular, the assignments at
131 and 202 belong to continuation branches, not the isLast call branch at191.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/router/trie-router/node.ts'


def git(checkout, *args):
    return subprocess.check_output(['git', '-C', str(checkout), *args])


def span(raw, first, last):
    lines = raw.splitlines(keepends=True)
    if len(lines) < last:
        raise ValueError('Pinned source window is outside source')
    start = sum(map(len, lines[:first-1]))
    end = sum(map(len, lines[:last]))
    return start, end, raw[start:end]


def artifacts(checkout):
    if git(checkout, 'rev-parse', 'HEAD').decode().strip() != REVISION:
        raise ValueError('Expected exact pinned Hono revision')
    if git(checkout, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('Expected clean pinned checkout; no reset is performed')
    raw = git(checkout, 'show', REVISION + ':' + SOURCE)
    if (checkout / SOURCE).read_bytes() != raw:
        raise ValueError('Working source bytes differ from pinned Git blob')
    selected = {name: (line, *span(raw, line, line)) for name, line in
                [('reset', 88), ('propagation', 109), ('wildcard', 131), ('parameter', 202)]}
    fragments = {name: dict(firstLine=line, lastLine=line, startByte=start,
        endByteExclusive=end, sha256=hashlib.sha256(data).hexdigest(),
        whitespacePolicy='Exact indentation and trailing LF retained')
        for name, (line, start, end, data) in selected.items()}
    start, end, method = span(raw, 86, 220)
    metadata = dict(schemaVersion=1, revision=REVISION,
        repository='https://github.com/honojs/hono.git', sourcePath=SOURCE,
        sourceGitBlob=git(checkout, 'rev-parse', REVISION + ':' + SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(raw).hexdigest(), fragments=fragments,
        containingMethod=dict(firstLine=86, lastLine=220, startByte=start,
            endByteExclusive=end, sha256=hashlib.sha256(method).hexdigest(),
            verificationStatus='Provenance only; selected writes parse independently, not complete search control flow.'),
        sourceSubset='Private DATA assignment, runtime this for reset, saved receiver/private identity before RHS, tagged PrivateSet after RHS.',
        controlFlowBoundary='Literal-child propagation109 precedes selected call115. Writes131/202 are continuation branches; any later call uses a separate explicit activation, not a claimed contiguous202-to191 branch.',
        kindBoundary='DATA/METHOD kind comes from tagged class installation, never from the stored Value or a desired output premise. Private accessors and full native language/heap adequacy remain open.',
        formalCompleteSearchTheorem=None, formalNativeActivationTheorem=None)
    lean = ('-- Generated by verification/private-write/source.py; source identity is externally checked.\n'
            'import HonoLean.Upstream.SourceSubset.Syntax\n\n'
            'namespace HonoLean.Upstream.NodePrivateWrite\n\n')
    for name, (_, _, _, data) in selected.items():
        lean += 'def pinned' + name.title() + 'Source : String := ' + json.dumps(data.decode('ascii')) + '\n\n'
    lean += 'end HonoLean.Upstream.NodePrivateWrite\n'
    outputs = {ROOT/'verification/private-write/source.json': (json.dumps(metadata, indent=2)+'\n').encode(),
        ROOT/'HonoLean/Upstream/NodePrivateWrite/Generated.lean': lean.encode()}
    outputs.update({ROOT/f'verification/private-write/{name}.ts.txt': data
                    for name, (_, _, _, data) in selected.items()})
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for path, data in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        elif not path.exists() or path.read_bytes() != data:
            raise SystemExit(f'Stale or changed source artifact: {path.relative_to(ROOT)}')
    print('Pinned private writes88/109/131/202 and Lean embeddings checked.')


if __name__ == '__main__':
    main()
