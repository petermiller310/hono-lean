#!/usr/bin/env python3
"""Bind the complete pinned methods loop, including its guard and capture body.

Extraction is external identity evidence. The containing method signature is
provenance, not a proof of class initialization, callers, or native activations.
--write refreshes only the source/metadata artifacts; the Lean owner creates the
embedding, which ordinary checking subsequently verifies byte-for-byte.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/router/trie-router/node.ts'
GENERATED = ROOT / 'HonoLean/Upstream/MethodsLoop/Generated.lean'


def git(checkout, *arguments):
    return subprocess.check_output(['git', '-C', str(checkout), *arguments])


def span(contents, first_line, last_line):
    lines = contents.splitlines(keepends=True)
    if len(lines) < last_line:
        raise ValueError('Pinned line span is outside source')
    start = sum(map(len, lines[:first_line - 1]))
    end = sum(map(len, lines[:last_line]))
    return start, end, contents[start:end]


def artifacts(checkout):
    actual = git(checkout, 'rev-parse', 'HEAD').decode().strip()
    if actual != REVISION:
        raise ValueError(f'Expected pinned revision {REVISION}, got {actual}')
    if git(checkout, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('Expected clean pinned Hono checkout; no reset is performed')
    contents = git(checkout, 'show', REVISION + ':' + SOURCE)
    if (checkout / SOURCE).read_bytes() != contents:
        raise ValueError('Working source bytes differ from pinned Git blob: ' + SOURCE)
    start, end, loop = span(contents, 71, 83)
    context_start, context_end, context = span(contents, 64, 84)
    metadata = dict(schemaVersion=1, repository='https://github.com/honojs/hono.git',
        revision=REVISION, sourcePath=SOURCE,
        sourceGitBlob=git(checkout, 'rev-parse', REVISION + ':' + SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(contents).hexdigest(),
        fragmentKind='complete Node.#pushHandlerSets outer methods loop',
        firstLine=71, lastLine=83, startByte=start, endByteExclusive=end,
        fragmentSha256=hashlib.sha256(loop).hexdigest(),
        whitespacePolicy='Exact source indentation and trailing LF are retained.',
        containingMethod=dict(name='Node.#pushHandlerSets', firstLine=64, lastLine=84,
            startByte=context_start, endByteExclusive=context_end,
            sha256=hashlib.sha256(context).hexdigest(), source=context.decode('ascii'),
            verificationStatus='The selected body loop is parsed; method signature, class initialization, callers and activation/argument transport remain outside this fragment.'),
        privateContext=dict(spelling='methods',
            status='Explicit lexical private-name identity and branded owner/slot supplied at fragment entry; actual class identity installation remains open.'),
        languageReference='ECMA-262 16th edition (2025)',
        sourceSubset='Private dense-array length/index; saved-length scoped counted loop; retained type assertion; lazy logical OR; truthy branch; parsed helper invocation; reset/append; nested scoped counted key loop and optional/nullish value selection.',
        linkage='External Git/line-span/embedding identity check plus kernel-checked generic fragment parsing; no complete TypeScript frontend, native engine or whole-Node source theorem.',
        formalSearchTraversalTheorem=None,
        formalClassInitializationTheorem=None,
        formalNativeActivationTheorem=None)
    lean = ('-- Generated by verification/methods-loop/source.py; source identity is externally checked.\n'
            'import HonoLean.Upstream.SourceSubset.Syntax\n\n'
            'namespace HonoLean.Upstream.MethodsLoop\n\n'
            'def pinnedSource : String := ' + json.dumps(loop.decode('ascii')) + '\n\n'
            'end HonoLean.Upstream.MethodsLoop\n')
    return {
        ROOT / 'verification/methods-loop/loop.ts.txt': loop,
        ROOT / 'verification/methods-loop/source.json': (json.dumps(metadata, indent=2) + '\n').encode(),
        GENERATED: lean.encode(),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for path, data in artifacts(args.hono).items():
        if args.write and path != GENERATED:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        elif args.write:
            continue
        elif not path.exists() or path.read_bytes() != data:
            raise SystemExit(f'Stale or changed source artifact: {path.relative_to(ROOT)}')
    print('Pinned complete methods loop lines71–83 and containing method context checked.'
        if not args.write else 'Pinned methods-loop source/metadata written; Lean embedding is checked separately.')


if __name__ == '__main__':
    main()
