#!/usr/bin/env python3
"""Pin real positive-lookahead fragments; source identity is not native adequacy."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

ROOT=Path(__file__).resolve().parents[2]
REVISION='5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE='src/utils/url.ts'
def git(checkout,*args):return subprocess.check_output(['git','-C',str(checkout),*args])
def sha(data):return hashlib.sha256(data).hexdigest()
def artifacts(checkout):
    if git(checkout,'rev-parse','HEAD').decode().strip()!=REVISION:raise ValueError('Expected exact pinned revision')
    if git(checkout,'status','--porcelain','--untracked-files=all').strip():raise ValueError('Expected clean checkout; no reset is performed')
    checked=0
    for entry in filter(None,git(checkout,'ls-tree','-rz',REVISION,'--','src','package.json').split(b'\0')):
        info,path=entry.split(b'\t',1);data=(checkout/path.decode()).read_bytes()
        if hashlib.sha1(b'blob '+str(len(data)).encode()+b'\0'+data).hexdigest()!=info.split()[2].decode():raise ValueError('Pinned blob differs: '+path.decode())
        checked+=1
    if checked!=315:raise ValueError('Expected 315 pinned blobs')
    raw=git(checkout,'show',REVISION+':'+SOURCE)
    if(checkout/SOURCE).read_bytes()!=raw:raise ValueError('Working source differs')
    lines=raw.splitlines(keepends=True);line=lines[66];offset=sum(map(len,lines[:66]))
    if(offset,len(line))!=(1644,75):raise ValueError('Expected original line67 byte span')
    constructor=line[line.index(b'new RegExp('):line.rindex(b']')]
    tuple_=line[line.index(b'['):line.rindex(b']')+1]
    if len(constructor)!=38 or len(tuple_)!=60:raise ValueError('Expected original constructor/tuple spans')
    body=raw[1344:1920]
    if body!=(ROOT/'verification/getpattern-body/body.ts.txt').read_bytes():raise ValueError('Reused complete body differs')
    generated=(ROOT/'HonoLean/Upstream/GetPatternBody/Generated.lean').read_text()
    literal=re.search(r'^def pinnedBody : String := (.+)$',generated,re.M)
    if literal is None or json.loads(literal[1]).encode()!=body:raise ValueError('Reused kernel body literal differs')
    pieces={'constructor':(1679,1717,67,constructor),'tuple':(1658,1718,67,tuple_),
            'line':(offset,offset+len(line),67,line)}
    for name,index in [('label-declaration',59),('key-declaration',61)]:
        start=sum(map(len,lines[:index]));pieces[name]=(start,start+len(lines[index]),index+1,lines[index])
    output={};fragments={}
    for name,(start,end,number,value)in pieces.items():
        if raw[start:end]!=value:raise ValueError('Incorrect fragment '+name)
        target='verification/getpattern-lookahead/'+name+'.ts.txt'
        fragments[name]=dict(firstLine=number,lastLine=number,startByte=start,endByteExclusive=end,sha256=sha(value),sourceCopy=target)
        output[ROOT/target]=value
    metadata=dict(schemaVersion=1,revision=REVISION,repository='https://github.com/honojs/hono.git',sourcePath=SOURCE,
        sourceGitBlob=git(checkout,'rev-parse',REVISION+':'+SOURCE).decode().strip(),sourceSha256=sha(raw),checkedPinnedBlobs=checked,
        fragments=fragments,reusedCompleteBody=dict(sourceMetadata='verification/getpattern-body/source.json',startByte=1344,endByteExclusive=1920,sha256=sha(body)),
        sourceBoundary='Actual38B constructor/60B tuple/75B line67 plus original60/62 declarations. Kernel source connection projects their real nodes from the already checked complete576B body AST; the fragments are not fabricated standalone conditional statements.',
        semanticBoundary='Selected actual60→62→67 expression composition and produced matcher semantics are separate proof obligations. Ancestor guards and branch reachability are NOT executed by this projection; full cache guards/Set/74 return and lexical-closure integration follow in the next checkpoint. Identity, native/type-erasure/module and general regex adequacy are not established by this checker.',
        formalCompleteGetPatternTheorem=None,formalCompleteCacheOrClosureTheorem=None,formalNativeLanguageAdequacyTheorem=None)
    lean='-- Generated by verification/getpattern-lookahead/source.py; identity is externally checked.\nimport HonoLean.Upstream.GetPatternBody.Generated\nnamespace HonoLean.Upstream.GetPatternLookahead\n\n'
    for name,key in [('pinnedConstructor','constructor'),('pinnedTuple','tuple'),('pinnedLine','line'),('pinnedLabelDeclaration','label-declaration'),('pinnedKeyDeclaration','key-declaration')]:
        lean+='def '+name+' : String := '+json.dumps(pieces[key][3].decode('ascii'))+'\n\n'
    lean+='def pinnedBody : String := HonoLean.Upstream.GetPatternBody.pinnedBody\n\nend HonoLean.Upstream.GetPatternLookahead\n'
    output[ROOT/'verification/getpattern-lookahead/source.json']=(json.dumps(metadata,indent=2)+'\n').encode()
    output[ROOT/'HonoLean/Upstream/GetPatternLookahead/Generated.lean']=lean.encode()
    return output
def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--hono',type=Path,required=True);parser.add_argument('--write',action='store_true');args=parser.parse_args()
    for path,data in artifacts(args.hono.resolve()).items():
        if args.write:path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
        elif not path.exists()or path.read_bytes()!=data:raise ValueError('Stale source artifact: '+str(path.relative_to(ROOT)))
    print('Pinned315blobs; actual67 constructor38B/tuple60B/line75B and actual60/62 declarations; reused576B kernel body literal exact.')
if __name__=='__main__':main()
