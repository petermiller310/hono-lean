#!/usr/bin/env python3
"""Bind contiguous87–119 and check its already-bound component spans."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT=Path(__file__).resolve().parents[2]
REVISION='5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE='src/router/trie-router/node.ts'
COMPONENTS=[('search-setup','startup',87,97),('loop-entry','outer',99,99),
    ('iteration-setup','iteration',100,102),('loop-entry','inner',104,104),
    ('iteration-setup','entry',105,119)]


def git(checkout,*args):
    return subprocess.check_output(['git','-C',str(checkout),*args])


def artifacts(checkout):
    if git(checkout,'rev-parse','HEAD').decode().strip()!=REVISION:
        raise ValueError('Expected exact pinned Hono revision')
    if git(checkout,'status','--porcelain','--untracked-files=all').strip():
        raise ValueError('Expected clean pinned checkout; no reset is performed')
    raw=git(checkout,'show',REVISION+':'+SOURCE)
    if (checkout/SOURCE).read_bytes()!=raw:
        raise ValueError('Working source differs from pinned Git blob')
    lines=raw.splitlines(keepends=True)
    start=sum(map(len,lines[:86]));end=sum(map(len,lines[:119]))
    full=raw[start:end]
    components=[]
    for folder,name,first,last in COMPONENTS:
        lo=sum(map(len,lines[:first-1]));hi=sum(map(len,lines[:last]))
        previous=json.loads((ROOT/f'verification/{folder}/source.json').read_text())
        if previous['revision']!=REVISION or previous['sourcePath']!=SOURCE or previous['sourceSha256']!=hashlib.sha256(raw).hexdigest():
            raise ValueError('Component source identity differs from pinned source')
        span=previous['fragments'][name]
        if (span['firstLine'],span['lastLine'],span['startByte'],span['endByteExclusive'],span['sha256'])!=(first,last,lo,hi,hashlib.sha256(raw[lo:hi]).hexdigest()):
            raise ValueError('Component span differs from contiguous source assembly')
        if (ROOT/f'verification/{folder}/{name}.ts.txt').read_bytes()!=raw[lo:hi]:
            raise ValueError('Component source copy differs from pinned source')
        components.append(dict(sourceMetadata=f'verification/{folder}/source.json',fragment=name,
            sourceCopy=f'verification/{folder}/{name}.ts.txt',firstLine=first,lastLine=last,
            startByte=lo,endByteExclusive=hi,sha256=hashlib.sha256(raw[lo:hi]).hexdigest()))
    if lines[97]!=b'\n' or lines[102]!=b'\n':
        raise ValueError('Expected only exact blank LF lines98/103 between components')
    assembled=(raw[components[0]['startByte']:components[0]['endByteExclusive']]+b'\n'+
        raw[components[1]['startByte']:components[1]['endByteExclusive']]+
        raw[components[2]['startByte']:components[2]['endByteExclusive']]+b'\n'+
        raw[components[3]['startByte']:components[3]['endByteExclusive']]+
        raw[components[4]['startByte']:components[4]['endByteExclusive']])
    if assembled!=full:
        raise ValueError('Component assembly does not cover the actual contiguous prefix')
    metadata=dict(schemaVersion=1,revision=REVISION,repository='https://github.com/honojs/hono.git',
        sourcePath=SOURCE,sourceGitBlob=git(checkout,'rev-parse',REVISION+':'+SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(raw).hexdigest(),
        fragment=dict(firstLine=87,lastLine=119,startByte=start,endByteExclusive=end,
            sha256=hashlib.sha256(full).hexdigest(),sourceCopy='verification/first-literal/full.ts.txt'),
        components=components,gaps=[dict(line=98,contents='LF'),dict(line=103,contents='LF')],
        parserBoundary='Explicit segmented startup/header/declaration/private-control prefix parsing. A kernel-checked string reassembly equation covers every character of87–119, including two blank LF gaps; no full TypeScript frontend or loop body/completion theorem.',
        semanticBoundary='Source-created collector, arrays, reset, first indices/guards and complete first literal branch; initial-only storage/record/read facts derive helper readiness. Pattern suffix, later iterations, queue progression, sorting and native adequacy remain open.',
        formalCompleteSearchTheorem=None,formalCompleteLoopBodyTheorem=None)
    lean=('-- Generated by verification/first-literal/source.py; source identity is externally checked.\n'
        'namespace HonoLean.Upstream.NodeFirstLiteral\n\n'
        'def pinnedFullSource : String := '+json.dumps(full.decode('ascii'))+'\n\n'
        'end HonoLean.Upstream.NodeFirstLiteral\n')
    return {ROOT/'verification/first-literal/source.json':(json.dumps(metadata,indent=2)+'\n').encode(),
        ROOT/'verification/first-literal/full.ts.txt':full,
        ROOT/'HonoLean/Upstream/NodeFirstLiteral/Generated.lean':lean.encode()}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono',type=Path,required=True)
    parser.add_argument('--write',action='store_true')
    args=parser.parse_args()
    for path,data in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
        elif not path.exists() or path.read_bytes()!=data:
            raise SystemExit(f'Stale or changed artifact: {path.relative_to(ROOT)}')
    print('Pinned contiguous87–119, all component spans and exact blank-line assembly checked.')


if __name__=='__main__':main()
