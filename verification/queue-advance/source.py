#!/usr/bin/env python3
"""Check the exact pinned Node.search queue-advance source and Lean embedding."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/router/trie-router/node.ts'


def git(checkout, *arguments):
    return subprocess.check_output(['git', '-C', str(checkout), *arguments])


def artifacts(checkout):
    if git(checkout, 'rev-parse', 'HEAD').decode().strip() != REVISION:
        raise ValueError('Expected the exact pinned Hono revision')
    if git(checkout, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('Expected a clean pinned checkout; no reset is performed')
    contents = git(checkout, 'show', REVISION + ':' + SOURCE)
    if (checkout / SOURCE).read_bytes() != contents:
        raise ValueError('Working source differs from the pinned Git blob')
    lines = contents.splitlines(keepends=True)
    start, end = sum(map(len, lines[:208])), sum(map(len, lines[:210]))
    fragment = contents[start:end]
    expected = (b'      const shifted = curNodesQueue.shift()\n'
                b'      curNodes = shifted ? tempNodes.concat(shifted) : tempNodes\n')
    if fragment != expected:
        raise ValueError('The selected lines are not the pinned queue-advance statements')
    metadata = dict(
        schemaVersion=1, repository='https://github.com/honojs/hono.git',
        revision=REVISION, sourcePath=SOURCE,
        sourceGitBlob=git(checkout, 'rev-parse', REVISION + ':' + SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(contents).hexdigest(),
        fragment=dict(firstLine=209, lastLine=210, startByte=start,
                      endByteExclusive=end, sha256=hashlib.sha256(fragment).hexdigest(),
                      sourceCopy='verification/queue-advance/source.ts.txt'),
        languageReference='ECMA-262 16th edition (2025)',
        parserBoundary='Explicit linear mutable-sequence entry reuses the shared lexer, expression syntax and statement boundaries; only supplied mutable outer bindings can be rebound. Existing block/function/private-control admission is unchanged.',
        semanticBoundary='Exact shift, conditional concat/reuse and first mutable curNodes binding replacement. Dense ordinary arrays and frozen standard intrinsics; native species/spreadability, exotic/sparse arrays, mutable lexical-cell adequacy and full loop/search remain open.',
        formalCompleteLoopTheorem=None, formalCompleteSearchTheorem=None)
    lean = ('-- Generated by verification/queue-advance/source.py; source identity is externally checked.\n'
            'namespace HonoLean.Upstream.NodeQueueAdvance\n\n'
            'def pinnedSource : String := ' + json.dumps(fragment.decode('ascii')) + '\n\n'
            'end HonoLean.Upstream.NodeQueueAdvance\n')
    return {
        ROOT / 'verification/queue-advance/source.ts.txt': fragment,
        ROOT / 'verification/queue-advance/source.json': (json.dumps(metadata, indent=2) + '\n').encode(),
        ROOT / 'HonoLean/Upstream/NodeQueueAdvance/Generated.lean': lean.encode(),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for path, data in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        elif not path.exists() or path.read_bytes() != data:
            raise SystemExit(f'Stale or changed artifact: {path.relative_to(ROOT)}')
    print('Pinned queue advance209–210 and exact Lean embedding checked.')


if __name__ == '__main__':
    main()
