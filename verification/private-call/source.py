#!/usr/bin/env python3
"""Bind the private helper declaration and two actual Node.search call entries.

The selected call-entry semantics covers declaration parameters, lexical/private
capture, ordered argument evaluation and the existing complete helper body.
Class method installation, surrounding search traversal and native adequacy are
separate obligations, not consequences of copying the complete declaration.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/router/trie-router/node.ts'


def git(checkout, *arguments):
    return subprocess.check_output(['git', '-C', str(checkout), *arguments])


def span(contents, first, last):
    lines = contents.splitlines(keepends=True)
    if len(lines) < last:
        raise ValueError('Pinned source window is outside source')
    start = sum(map(len, lines[:first-1]))
    end = sum(map(len, lines[:last]))
    return start, end, contents[start:end]


def artifacts(checkout):
    actual = git(checkout, 'rev-parse', 'HEAD').decode().strip()
    if actual != REVISION:
        raise ValueError(f'Expected pinned revision {REVISION}, got {actual}')
    if git(checkout, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('Expected clean pinned Hono checkout; no reset is performed')
    contents = git(checkout, 'show', REVISION + ':' + SOURCE)
    if (checkout / SOURCE).read_bytes() != contents:
        raise ValueError('Working source bytes differ from pinned Git blob')
    selected = {name: (first, last, *span(contents, first, last))
                for name, first, last in [('method', 64, 84), ('four', 115, 115), ('five', 191, 191)]}
    fragments = {}
    for name, (first, last, start, end, data) in selected.items():
        fragments[name] = dict(sourcePath=SOURCE, firstLine=first, lastLine=last,
            startByte=start, endByteExclusive=end, sha256=hashlib.sha256(data).hexdigest(),
            whitespacePolicy='Exact source indentation and trailing LF retained')
    metadata = dict(schemaVersion=1, repository='https://github.com/honojs/hono.git',
        revision=REVISION, sourcePath=SOURCE,
        sourceSha256=hashlib.sha256(contents).hexdigest(),
        sourceGitBlob=git(checkout, 'rev-parse', REVISION + ':' + SOURCE).decode().strip(),
        fragments=fragments,
        methodParameters=['handlerSets', 'node', 'method', 'nodeParams', 'params'],
        optionalParameter='params',
        bodyDependency='verification/methods-loop/source.json: exact helper loop lines71–83',
        callEntries=dict(four='Exact literal-child call, fifth argument omitted',
            five='Exact simple-parameter call: fourth is params, fifth is node.#params'),
        sourceSubset='Private method signature with retained parameter/return type metadata; top-level private member call with explicit dynamic this; existing supported argument expressions and full counted capture body.',
        boundary='Method closure and private read handle are explicit source-bound inputs. Private method installation/read-only enforcement, complete class/module/live lexical cells, surrounding search traversal, nested arbitrary block calls and native interpretation remain open.',
        formalCompleteClassTheorem=None, formalSearchTraversalTheorem=None,
        formalNativeActivationTheorem=None)
    lean = ('-- Generated by verification/private-call/source.py; source identity is externally checked.\n'
            'import HonoLean.Upstream.SourceSubset.Syntax\n\n'
            'namespace HonoLean.Upstream.NodePrivateCall\n\n')
    for name, (_, _, _, _, data) in selected.items():
        lean += 'def pinned' + name.title() + 'Source : String := ' + json.dumps(data.decode('ascii')) + '\n\n'
    lean += 'end HonoLean.Upstream.NodePrivateCall\n'
    outputs = {ROOT/'verification/private-call/source.json': (json.dumps(metadata, indent=2)+'\n').encode(),
               ROOT/'HonoLean/Upstream/NodePrivateCall/Generated.lean': lean.encode()}
    outputs.update({ROOT/('verification/private-call/'+('method' if name == 'method' else 'call-'+name)+'.ts.txt'): data
                    for name, (_, _, _, _, data) in selected.items()})
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for path, data in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        elif not path.exists() or path.read_bytes() != data:
            raise SystemExit(f'Stale or changed source artifact: {path.relative_to(ROOT)}')
    print('Pinned private declaration64–84, call entries115/191 and embeddings checked.')


if __name__ == '__main__':
    main()
