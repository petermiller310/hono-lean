#!/usr/bin/env python3
"""Bind Hono's actual terminal tuple/NewExpression, not its enclosing branch."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/utils/url.ts'
SPANS = {
    'full': (1733, 1779, 'b70aef226ab3fc4a7ec886b9d64dbace87107beb4989920d05b48f6bd6b86560'),
    'constructor': (1751, 1778, 'e242febcd54382c8ec740fa0ebf010a1992290e980475f709cbeb7117759e571'),
    'line': (1719, 1780, '3c6f870d1856364a2beb399570d2546e3370927dbe644b68b644eb102f51afec'),
}


def git(checkout, *args):
    return subprocess.check_output(['git', '-C', str(checkout), *args])


def artifacts(checkout):
    if git(checkout, 'rev-parse', 'HEAD').decode().strip() != REVISION:
        raise ValueError('Expected exact pinned Hono revision')
    if git(checkout, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('Expected clean checkout; no reset is performed')
    raw = git(checkout, 'show', REVISION + ':' + SOURCE)
    if (checkout / SOURCE).read_bytes() != raw:
        raise ValueError('Working source differs from pinned Git bytes')
    fragments, contents = {}, {}
    for name, (start, end, expected) in SPANS.items():
        source = raw[start:end]
        if hashlib.sha256(source).hexdigest() != expected:
            raise ValueError('Expected original pinned ' + name + ' bytes')
        copy = 'verification/pattern-construct/' + name + '.ts.txt'
        fragments[name] = dict(firstLine=68, lastLine=68, startByte=start,
                              endByteExclusive=end, sha256=expected, sourceCopy=copy)
        contents[ROOT / copy] = source
    metadata = dict(schemaVersion=1, revision=REVISION, repository='https://github.com/honojs/hono.git',
        sourcePath=SOURCE, sourceGitBlob=git(checkout, 'rev-parse', REVISION + ':' + SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(raw).hexdigest(), fragments=fragments,
        languageReference='ECMA-262, 16th edition (2025)',
        sourceBoundary='Actual46B selected terminal tuple expression and contained27B NewExpression; full61B line retains surrounding colon only as identity context. Not the enclosing65-68 conditional, cache assignment or complete getPattern.',
        semanticBoundary='Retained template/New/array AST, current constructor identity and actual dense match1/name match2/body reads. Derive fresh tuple and regex ordinary cell/lastIndex plus genuine parsed compiled internal record, preserving evaluation/allocation order. Standard constructor/prototype/newTarget interpretation remains explicit. No supplied branded record/compiled result/tuple input.',
        formalCompleteGetPatternTheorem=None, formalCompleteSearchTheorem=None,
        formalNativeLanguageAdequacyTheorem=None)
    contents[ROOT / 'verification/pattern-construct/source.json'] = (json.dumps(metadata, indent=2) + '\n').encode()
    lean = '-- Generated by verification/pattern-construct/source.py; identity is externally checked.\nnamespace HonoLean.Upstream.PatternConstruct\n\n'
    for name, constant in [('full', 'pinnedSource'), ('constructor', 'pinnedConstructor'), ('line', 'pinnedLine')]:
        lean += 'def ' + constant + ' : String := ' + json.dumps(contents[ROOT / fragments[name]['sourceCopy']].decode('ascii')) + '\n\n'
    lean += 'end HonoLean.Upstream.PatternConstruct\n'
    contents[ROOT / 'HonoLean/Upstream/PatternConstruct/Generated.lean'] = lean.encode()
    return contents


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for path, contents in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(contents)
        elif not path.exists() or path.read_bytes() != contents:
            raise SystemExit(f'Stale or changed artifact: {path.relative_to(ROOT)}')
    print('Pinned actual46B tuple/27B constructor and61B line context checked.')


if __name__ == '__main__': main()
