#!/usr/bin/env python3
"""Bind three actual pinned Node.insert operations to Lean source embeddings.

Line/window selection is an external identity check, not a TS frontend. Lean
parses each exact selected operation. The supplied add trace is not a checked
translation of Node.insert traversal, branch selection, or pattern production.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/router/trie-router/node.ts'


def git(checkout, *arguments):
    return subprocess.check_output(['git', '-C', str(checkout), *arguments])


def span(contents, first, last):
    lines = contents.splitlines(keepends=True)
    start = sum(map(len, lines[:first - 1]))
    end = sum(map(len, lines[:last]))
    return start, end, contents[start:end]


def artifacts(checkout):
    actual = git(checkout, 'rev-parse', 'HEAD').decode().strip()
    if actual != REVISION:
        raise ValueError(f'Expected pinned revision {REVISION}, got {actual}')
    if git(checkout, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('Expected a clean pinned Hono checkout; no reset is performed')
    contents = git(checkout, 'show', REVISION + ':' + SOURCE)
    if (checkout / SOURCE).read_bytes() != contents:
        raise ValueError('Working source bytes differ from the pinned Git blob')
    selected = {'create': span(contents, 33, 33), 'add': span(contents, 51, 51)}
    line_start, _, line = span(contents, 58, 58)
    begin = line.index(b'[')
    stop = line.index(b']', begin) + 1
    selected['spread'] = (line_start + begin, line_start + stop, line[begin:stop])
    fragments = {}
    for name, (start, end, fragment) in selected.items():
        first = 33 if name == 'create' else 51 if name == 'add' else 58
        fragments[name] = dict(firstLine=first, lastLine=first, startByte=start,
            endByteExclusive=end, sha256=hashlib.sha256(fragment).hexdigest(),
            whitespacePolicy='Exact indentation and LF retained' if name != 'spread'
                else 'Exact expression window; no indentation, field label, comma or LF added')
    context_start, context_end, context = span(contents, 28, 62)
    metadata = dict(schemaVersion=1, repository='https://github.com/honojs/hono.git',
        revision=REVISION, sourcePath=SOURCE,
        sourceGitBlob=git(checkout, 'rev-parse', REVISION + ':' + SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(contents).hexdigest(), fragments=fragments,
        containingMethod=dict(name='Node.insert', firstLine=28, lastLine=62,
            startByte=context_start, endByteExclusive=context_end,
            sha256=hashlib.sha256(context).hexdigest(), source=context.decode('ascii'),
            verificationStatus='Provenance context only; insertion traversal is not parsed or verified'),
        languageReference='ECMA-262 16th edition (2025)',
        sourceSubset='Generic constructor with retained string type-argument metadata; method add with indexed argument; array literal spread',
        traceScope='Finite supplied sequence of successful primitive-string Add events; no proof of Node.insert branch/trace/string-key production',
        nativeBoundary='Standard constructor/add/iterator dispatch and no interleaved iterator mutation; TS erasure/native engine adequacy remain open',
        formalInsertTraversalTheorem=None)
    lean = ('-- Generated by verification/key-set/source.py; source identity is externally checked.\n'
            'import HonoLean.Upstream.SourceSubset.Syntax\n\n'
            'namespace HonoLean.Upstream.NodeKeySet\n\n')
    for name, (_, _, fragment) in selected.items():
        lean += 'def pinned' + name.title() + 'Source : String := ' + json.dumps(fragment.decode('ascii')) + '\n\n'
    lean += 'end HonoLean.Upstream.NodeKeySet\n'
    outputs = {ROOT / 'verification/key-set/source.json': (json.dumps(metadata, indent=2) + '\n').encode(),
        ROOT / 'HonoLean/Upstream/NodeKeySet/Generated.lean': lean.encode()}
    outputs.update({ROOT / ('verification/key-set/' + name + '.ts.txt'): fragment
        for name, (_, _, fragment) in selected.items()})
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for path, data in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        elif not path.exists() or path.read_bytes() != data:
            raise SystemExit(f'Stale or changed source artifact: {path.relative_to(ROOT)}')
    print('Pinned Set create/add/spread operations and insertion context checked.')


if __name__ == '__main__':
    main()
