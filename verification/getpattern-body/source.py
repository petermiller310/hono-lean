def git(checkout,*args):return subprocess.check_output(['git','-C',str(checkout),*args])
def artifacts(checkout):
    if git(checkout,'rev-parse','HEAD').decode().strip()!=REVISION:raise ValueError('Expected exact pinned revision')
    if git(checkout,'status','--porcelain','--untracked-files=all').strip():raise ValueError('Expected clean checkout; no reset is performed')
    blobs=git(checkout,'ls-tree','-rz',REVISION,'--','src','package.json').split(b'\0')
    checked=0
    for entry in filter(None,blobs):
        info,path=entry.split(b'\t',1);data=(checkout/path.decode()).read_bytes()
        actual=hashlib.sha1(b'blob '+str(len(data)).encode()+b'\0'+data).hexdigest()
        if actual!=info.split()[2].decode():raise ValueError('Pinned blob differs: '+path.decode())
        checked+=1
    if checked!=315:raise ValueError('Expected315 pinned blobs')
    raw=git(checkout,'show',REVISION+':'+SOURCE)
    if(checkout/SOURCE).read_bytes()!=raw:raise ValueError('Working source differs')
    lines=raw.splitlines(keepends=True);fragments={};files={};texts={}
