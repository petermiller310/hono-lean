#!/usr/bin/env python3
"""Bind actual Hono node138 ArrayBindingPattern to the new source entry."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/router/trie-router/node.ts'
DIGEST = '4bd90c878a3496b7a05edc1a3a90ba0e83afc24484b15acd1e600d5aff95a2a1'


def git(checkout, *args):
    return subprocess.check_output(['git','-C',str(checkout),*args])


def artifacts(checkout):
    if git(checkout,'rev-parse','HEAD').decode().strip() != REVISION:
        raise ValueError('Expected exact pinned Hono revision')
    if git(checkout,'status','--porcelain','--untracked-files=all').strip():
        raise ValueError('Expected clean checkout; no reset is performed')
    raw = git(checkout,'show',REVISION+':'+SOURCE)
    if (checkout/SOURCE).read_bytes() != raw:
        raise ValueError('Working source differs from pinned Git bytes')
    source = raw[4205:4249]
    if len(source) != 44 or hashlib.sha256(source).hexdigest() != DIGEST:
        raise ValueError('Expected actual44B138 bytes')
    if raw.splitlines(keepends=True)[137] != source:
        raise ValueError('Expected complete original138 line')
    fragment = dict(firstLine=138,lastLine=138,startByte=4205,endByteExclusive=4249,
                    sha256=DIGEST,sourceCopy='verification/pattern-binding/full.ts.txt')
    metadata = dict(schemaVersion=1,revision=REVISION,repository='https://github.com/honojs/hono.git',
        sourcePath=SOURCE,sourceGitBlob=git(checkout,'rev-parse',REVISION+':'+SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(raw).hexdigest(),fragments=dict(full=fragment),
        languageReference='ECMA-262, 16th edition (2025)',
        sourceBoundary='Complete actual44B const declaration/ArrayBindingPattern with first elision and name/matcher lexical bindings. Not index-read sugar, containing pattern loop, private pattern installation or all of Node.search.',
        semanticBoundary='Closed default-array iterator protocol uses current array reference/heap, saved next method, elision Step, binding StepValue and current full-chain missing-return Close. Fresh selected activation/flat lexical environment and standard symbol/intrinsic/prototype/native interpretation remain explicit. Constructor composition must derive tuple/brand/name/matcher, not receive completed outputs. restPathString146-154 preparation remains separate.',
        nativeBoundary='ENGINE-ELISION-1 custom iterator result0.value Bun extraGet/Node skip remains frozen native-only evidence, outside the closed default-DATA domain. No comparison baseline or allowlist change.',
        formalCompleteSearchTheorem=None,formalGeneralIteratorAdequacyTheorem=None,
        formalNativeLanguageAdequacyTheorem=None)
    lean = '-- Generated by verification/pattern-binding/source.py; identity is externally checked.\nnamespace HonoLean.Upstream.NodePatternBinding\n\n'
    lean += 'def pinnedSource : String := '+json.dumps(source.decode('ascii'))+'\n\n'
    lean += 'end HonoLean.Upstream.NodePatternBinding\n'
    return {ROOT/'verification/pattern-binding/full.ts.txt':source,
            ROOT/'verification/pattern-binding/source.json':(json.dumps(metadata,indent=2)+'\n').encode(),
            ROOT/'HonoLean/Upstream/NodePatternBinding/Generated.lean':lean.encode()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono',type=Path,required=True)
    parser.add_argument('--write',action='store_true')
    args = parser.parse_args()
    for path,contents in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_bytes(contents)
        elif not path.exists() or path.read_bytes() != contents:
            raise SystemExit(f'Stale or changed artifact: {path.relative_to(ROOT)}')
    print('Pinned actual44B138 ArrayBindingPattern checked.')


if __name__=='__main__':main()
