#!/usr/bin/env python3
"""Bind the pinned lazy path-offset block and suffix declaration to source."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/router/trie-router/node.ts'


def git(checkout, *args):
    return subprocess.check_output(['git', '-C', str(checkout), *args])


def artifacts(checkout):
    if git(checkout, 'rev-parse', 'HEAD').decode().strip() != REVISION:
        raise ValueError('Expected exact pinned Hono revision')
    if git(checkout, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('Expected clean pinned checkout; no reset is performed')
    raw = git(checkout, 'show', REVISION + ':' + SOURCE)
    if (checkout / SOURCE).read_bytes() != raw:
        raise ValueError('Working source differs from pinned Git bytes')
    lines, fragments, copies = raw.splitlines(keepends=True), {}, {}
    for name, first, last in [('full', 146, 154), ('prepare', 146, 153), ('slice', 154, 154)]:
        start, end = sum(map(len, lines[:first - 1])), sum(map(len, lines[:last]))
        contents = raw[start:end]
        fragments[name] = dict(firstLine=first, lastLine=last, startByte=start,
            endByteExclusive=end, sha256=hashlib.sha256(contents).hexdigest(),
            sourceCopy=f'verification/part-offsets/{name}.ts.txt')
        copies[name] = contents
    if fragments['full']['sha256'] != '25d15d9b81bc22ba038dea387a703528896940949ae50f9f2f1163c0be9a65c9':
        raise ValueError('Expected exact lazy offset/slice source146–154')
    if copies['prepare'] + copies['slice'] != copies['full']:
        raise ValueError('Preparation and slice do not reassemble the source')
    metadata = dict(schemaVersion=1, revision=REVISION,
        repository='https://github.com/honojs/hono.git', sourcePath=SOURCE,
        sourceGitBlob=git(checkout, 'rev-parse', REVISION + ':' + SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(raw).hexdigest(), fragments=fragments,
        languageReference='ECMA-262, 16th edition (2025)',
        sourceBoundary='Complete original lazy if/counted-for/indexed writes/+ and += operators/slice declaration;338=276+62 checked reassembly. Earlier splitPath/startup are separate pinned proof dependencies; matcher.exec156 and containing search are not included.',
        semanticBoundary='Initial primitive UTF16 path, actual dense string parts/saved bounds, outer cache binding and integer-specialized arithmetic with explicit native exactness/array/resource premises. Fresh table derived by actual source loop; truthy cache reused without repair. Correct suffix needs proved split alignment/no-truncation or a source-produced cache, never an assumed desired output.',
        supportingSourceChecks=['verification/splitpath/source.py', 'verification/search-setup/source.py'],
        formalCompleteSearchTheorem=None, formalNativeLanguageAdequacyTheorem=None)
    lean = '-- Generated by verification/part-offsets/source.py; identity is externally checked.\nnamespace HonoLean.Upstream.NodePartOffsets\n\n'
    for name, constant in [('full', 'pinnedSource'), ('prepare', 'pinnedPrepare'), ('slice', 'pinnedSlice')]:
        lean += 'def ' + constant + ' : String := ' + json.dumps(copies[name].decode('ascii')) + '\n\n'
    lean += 'end HonoLean.Upstream.NodePartOffsets\n'
    result = {ROOT / fragments[name]['sourceCopy']: contents for name, contents in copies.items()}
    result[ROOT / 'verification/part-offsets/source.json'] = (json.dumps(metadata, indent=2) + '\n').encode()
    result[ROOT / 'HonoLean/Upstream/NodePartOffsets/Generated.lean'] = lean.encode()
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for path, contents in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(contents)
        elif not path.exists() or path.read_bytes() != contents:
            raise SystemExit(f'Stale or changed artifact: {path.relative_to(ROOT)}')
    print('Pinned146–154 offsets/slice and276+62 byte reassembly checked.')


if __name__ == '__main__':
    main()
