#!/usr/bin/env python3
"""Bind Hono's actual capturing label-match declaration and regex literal."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/utils/url.ts'
SPANS = {
    'full': (1387,1446,'e1a741ae801aec83c5926a9d2b71e0b2a6dce9ee29406ef602a8d54a862d0207'),
    'call': (1403,1445,'a98a32751f6acbeab063921e57fd41e2e4bd7a27840a95f957c3ea1e823fbad8'),
    'literal': (1415,1444,'47817d28fa608a72aa9430717bf92373f21dec0f2b85758148b99d8d5a89ee94'),
}

def git(checkout,*args):
    return subprocess.check_output(['git','-C',str(checkout),*args])

def artifacts(checkout):
    if git(checkout,'rev-parse','HEAD').decode().strip()!=REVISION:
        raise ValueError('Expected exact pinned Hono revision')
    if git(checkout,'status','--porcelain','--untracked-files=all').strip():
        raise ValueError('Expected clean pinned checkout; no reset is performed')
    raw=git(checkout,'show',REVISION+':'+SOURCE)
    if (checkout/SOURCE).read_bytes()!=raw:
        raise ValueError('Working source differs from pinned Git bytes')
    fragments={};files={};texts={}
    for name,(start,end,digest) in SPANS.items():
        text=raw[start:end]
        if hashlib.sha256(text).hexdigest()!=digest:
            raise ValueError(f'Expected original {name} bytes/hash')
        copy='verification/label-match/'+name+'.ts.txt'
        files[ROOT/copy]=text
        texts[name]=text.decode('ascii')
        fragments[name]=dict(firstLine=60,lastLine=60,startByte=start,endByteExclusive=end,sha256=digest,sourceCopy=copy)
    if raw.splitlines(keepends=True)[59]!=texts['full'].encode():
        raise ValueError('Expected complete actual line60 including LF')
    if texts['literal']!=texts['call'][len('label.match('):-1]:
        raise ValueError('Expected genuine literal argument source relation')
    texts['pattern']=texts['literal'][1:-1]
    metadata=dict(schemaVersion=1,revision=REVISION,repository='https://github.com/honojs/hono.git',
        sourcePath=SOURCE,sourceGitBlob=git(checkout,'rev-parse',REVISION+':'+SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(raw).hexdigest(),fragments=fragments,
        languageReference='ECMA-262, 16th edition (2025)',
        sourceBoundary='Actual59B const declaration,42B method call and29B regular expression literal. The containing wildcard guard, if/cache/terminal branch and getPattern function are separate source obligations.',
        semanticBoundary='Retained regex syntax and genuine capturing operational execution; primitive current String.match, intrinsic literal creation, typed Symbol.match/current flags/exec dispatch under explicit initial standard-realm interpretation. Independent UTF16 label decomposition, capture values/spans and fresh capture-array/frame contract. No desired capture array or trusted label parser input.',
        nativeBoundary='Native unwrapped selected declaration and optional selected later activations; finite observations and wrappers/JSON/engine/frontend/realm interpretation remain unverified. Hidden compiled records and protocol events are model-only. ENGINE-FLAGS-1 preserves the pinned Node direct-global versus Bun selected-2025 flags path, with an observable throwing-flags-getter reproducer; no native protocol equality or new comparison allowance.',
        formalCompleteGetPatternTheorem=None,formalCompleteSearchTheorem=None,formalNativeLanguageAdequacyTheorem=None)
    files[ROOT/'verification/label-match/source.json']=(json.dumps(metadata,indent=2)+'\n').encode()
    lean='-- Generated by verification/label-match/source.py; identity is externally checked.\nnamespace HonoLean.Upstream.LabelMatch\n\n'
    for name,key in [('pinnedSource','full'),('pinnedCall','call'),('pinnedLiteral','literal'),('pinnedPattern','pattern')]:
        lean+='def '+name+' : String := '+json.dumps(texts[key])+'\n\n'
    lean+='end HonoLean.Upstream.LabelMatch\n'
    files[ROOT/'HonoLean/Upstream/LabelMatch/Generated.lean']=lean.encode()
    return files

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono',type=Path,required=True)
    parser.add_argument('--write',action='store_true')
    args=parser.parse_args()
    for path,contents in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_bytes(contents)
        elif not path.exists() or path.read_bytes()!=contents:
            raise SystemExit(f'Stale or changed artifact: {path.relative_to(ROOT)}')
    print('Pinned actual59B url60 /42B call/29B regex literal checked.')

if __name__=='__main__':main()
