#!/usr/bin/env python3
"""Untrusted source embedding/freshness checker; Lean checks parsing separately."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/utils/url.ts'

def git(checkout, *arguments):
    return subprocess.check_output(['git', '-C', str(checkout), *arguments])

def extract(contents):
    start = contents.index(b'export const splitPath =')
    opening = contents.index(b'{', start)
    depth = 0
    quote = None
    escaped = False
    for index in range(opening, len(contents)):
        char = contents[index]
        if quote:
            if escaped:
                escaped = False
            elif char == 92:
                escaped = True
            elif char == quote:
                quote = None
        elif char in (34, 39):
            quote = char
        elif char == 123:
            depth += 1
        elif char == 125:
            depth -= 1
            if depth == 0:
                return start, index + 1, contents[start:index + 1]
    raise ValueError('Unterminated function')

def artifacts(checkout):
    actual = git(checkout, 'rev-parse', 'HEAD').decode().strip()
    if actual != REVISION:
        raise ValueError(f'Expected pinned revision {REVISION}, got {actual}')
    if git(checkout, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('Expected a clean pinned Hono checkout; no reset is performed')
    contents = git(checkout, 'show', REVISION + ':' + SOURCE)
    if (checkout/SOURCE).read_bytes() != contents:
        raise ValueError('Working source bytes differ from the pinned Git blob')
    start, end, function = extract(contents)
    body = function.decode('ascii')
    metadata = dict(schemaVersion=1, repository='https://github.com/honojs/hono.git',
        revision=REVISION, sourcePath=SOURCE,
        sourceGitBlob=git(checkout, 'rev-parse', REVISION + ':' + SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(contents).hexdigest(),
        functionName='splitPath', startByte=start, endByteExclusive=end,
        functionSha256=hashlib.sha256(function).hexdigest(),
        languageReference='ECMA-262 16th edition (2025)',
        sourceSubset='ASCII function declaration, checked annotations, const/if/return, member calls, index, strict equality',
        splitDefaultLimit=4294967295, maximumStringLength=9007199254740991,
        linkage='External Git/extraction/embedding checker plus kernel-checked Lean parsing; not a verified whole TypeScript frontend')
    lean = ('-- Generated by verification/splitpath/source.py; extraction is independently checked.\n'
            'import HonoLean.Upstream.SourceSubset.Syntax\n\n'
            'namespace HonoLean.Upstream.SourceSubset\n\n'
            'def pinnedSource : String := ' + json.dumps(body) + '\n\n'
            'end HonoLean.Upstream.SourceSubset\n')
    return {ROOT/'verification/splitpath/splitPath.ts.txt': function,
            ROOT/'verification/splitpath/source.json': (json.dumps(metadata, indent=2)+'\n').encode(),
            ROOT/'HonoLean/Upstream/SourceSubset/Generated.lean': lean.encode()}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono', type=Path, required=True)
    parser.add_argument('--write', action='store_true', help='Regenerate the three source identity artifacts')
    args = parser.parse_args()
    for path, data in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        elif not path.exists() or path.read_bytes() != data:
            raise SystemExit(f'Stale or changed source artifact: {path.relative_to(ROOT)}')
    print('Pinned source identity and exact extracted/embedded bytes checked.')

if __name__ == '__main__':
    main()
