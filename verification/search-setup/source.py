#!/usr/bin/env python3
"""Bind the contiguous Node.search startup declarations and private reset."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/router/trie-router/node.ts'


def git(checkout, *args):
    return subprocess.check_output(['git', '-C', str(checkout), *args])


def artifacts(checkout):
    if git(checkout, 'rev-parse', 'HEAD').decode().strip() != REVISION:
        raise ValueError('Expected exact pinned Hono revision')
    if git(checkout, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('Expected clean pinned checkout; no reset is performed')
    raw = git(checkout, 'show', REVISION + ':' + SOURCE)
    if (checkout / SOURCE).read_bytes() != raw:
        raise ValueError('Working source bytes differ from pinned Git blob')
    lines = raw.splitlines(keepends=True)
    start = sum(map(len, lines[:86]))
    end = sum(map(len, lines[:97]))
    fragment = raw[start:end]
    metadata = dict(schemaVersion=1, revision=REVISION,
        repository='https://github.com/honojs/hono.git', sourcePath=SOURCE,
        sourceGitBlob=git(checkout, 'rev-parse', REVISION + ':' + SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(raw).hexdigest(),
        fragments=dict(startup=dict(firstLine=87, lastLine=97, startByte=start,
            endByteExclusive=end, sha256=hashlib.sha256(fragment).hexdigest(),
            whitespacePolicy='Exact indentation, comment, blank lines and trailing LF retained')),
        sourceSubset='Contiguous startup declarations, runtime this alias, private DATA reset, fresh dense arrays, actual imported splitPath call, saved length and nullable offset declaration.',
        callBoundary='The explicit string-function table supplies the parsed splitPath closure/import identity. Its actual body executes on the current heap; caller environment, private names and runtime this are restored. Selected body does not read this; the function-call model uses module-undefined this.',
        controlFlowBoundary='Search headers99/104, traversal reachability, other branches and native module/transpiler/realm/heap adequacy remain open. Subsequent iteration/node selection uses explicit separately supplied index activations.',
        formalCompleteSearchTheorem=None, formalNativeModuleLinkingTheorem=None)
    lean = ('-- Generated by verification/search-setup/source.py; source identity is externally checked.\n'
            'namespace HonoLean.Upstream.NodeSearchSetup\n\n'
            'def pinnedSource : String := ' + json.dumps(fragment.decode('ascii')) + '\n\n'
            'end HonoLean.Upstream.NodeSearchSetup\n')
    return {ROOT/'verification/search-setup/source.json': (json.dumps(metadata, indent=2)+'\n').encode(),
        ROOT/'verification/search-setup/startup.ts.txt': fragment,
        ROOT/'HonoLean/Upstream/NodeSearchSetup/Generated.lean': lean.encode()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for path, data in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        elif not path.exists() or path.read_bytes() != data:
            raise SystemExit(f'Stale or changed source artifact: {path.relative_to(ROOT)}')
    print('Pinned contiguous search startup87–97 and Lean embedding checked.')


if __name__ == '__main__':
    main()
