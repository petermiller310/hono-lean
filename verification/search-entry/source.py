#!/usr/bin/env python3
"""Bind noncontiguous actual collector, row, selection and ALL initializer.

The collector is node.ts87 (line90 is a comment). Containing functions and the
export declaration are provenance, not a translation of search/module linking.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
NODE = 'src/router/trie-router/node.ts'
ROUTER = 'src/router.ts'


def git(checkout, *arguments):
    return subprocess.check_output(['git', '-C', str(checkout), *arguments])


def span(contents, first, last):
    lines = contents.splitlines(keepends=True)
    start = sum(map(len, lines[:first - 1]))
    end = sum(map(len, lines[:last]))
    return start, end, contents[start:end]


def artifacts(checkout):
    actual = git(checkout, 'rev-parse', 'HEAD').decode().strip()
    if actual != REVISION:
        raise ValueError(f'Expected pinned revision {REVISION}, got {actual}')
    if git(checkout, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('Expected clean pinned Hono checkout; no reset is performed')
    sources = {}
    contents = {}
    for source in [NODE, ROUTER]:
        data = git(checkout, 'show', REVISION + ':' + source)
        if (checkout / source).read_bytes() != data:
            raise ValueError('Working source bytes differ from pinned Git blob: ' + source)
        contents[source] = data
        sources[source] = dict(sha256=hashlib.sha256(data).hexdigest(),
            gitBlob=git(checkout, 'rev-parse', REVISION + ':' + source).decode().strip())
    selected = {name: (NODE, line, *span(contents[NODE], line, line))
        for name, line in [('collector', 87), ('row', 72), ('selection', 73)]}
    all_start, _, line = span(contents[ROUTER], 9, 9)
    begin = line.index(b'=') + 2
    end = len(line.rstrip(b'\n'))
    selected['all'] = (ROUTER, 9, all_start + begin, all_start + end, line[begin:end])
    fragments = {}
    for name, (source, line, start, end, data) in selected.items():
        fragments[name] = dict(sourcePath=source, firstLine=line, lastLine=line,
            startByte=start, endByteExclusive=end, sha256=hashlib.sha256(data).hexdigest(),
            whitespacePolicy='Exact declaration indentation and LF retained' if name != 'all'
                else 'Exact initializer expression; excludes export/const/name/equal prefix and following LF')
    contexts = {}
    for name, first, last in [('pushHandlerSets', 64, 84), ('search', 86, 220)]:
        start, end, data = span(contents[NODE], first, last)
        contexts[name] = dict(sourcePath=NODE, firstLine=first, lastLine=last,
            startByte=start, endByteExclusive=end, sha256=hashlib.sha256(data).hexdigest(),
            source=data.decode('ascii'), verificationStatus='Provenance only; surrounding traversal/outer method loop not parsed')
    metadata = dict(schemaVersion=1, repository='https://github.com/honojs/hono.git', revision=REVISION,
        sourcePath=NODE, sourceSha256=sources[NODE]['sha256'], sourceGitBlob=sources[NODE]['gitBlob'],
        sources=sources, fragments=fragments, containingContexts=contexts,
        collectorLineCorrection='Actual typed collector is line87; line90 is an eslint comment',
        sourceSubset='Retained type metadata; typed declaration; lazy value-returning logical OR; direct private row indexing; const assertion',
        moduleBoundary='Actual ALL initializer is parsed; module export/import linking and binding identity remain explicit',
        formalSearchTraversalTheorem=None, formalOuterMethodLoopTheorem=None)
    lean = ('-- Generated by verification/search-entry/source.py; source identity is externally checked.\n'
            'import HonoLean.Upstream.SourceSubset.Syntax\n\nnamespace HonoLean.Upstream.SearchEntry\n\n')
    for name, (_, _, _, _, data) in selected.items():
        lean += 'def pinned' + name.title() + 'Source : String := ' + json.dumps(data.decode('ascii')) + '\n\n'
    lean += 'end HonoLean.Upstream.SearchEntry\n'
    outputs = {ROOT / 'verification/search-entry/source.json': (json.dumps(metadata, indent=2) + '\n').encode(),
        ROOT / 'HonoLean/Upstream/SearchEntry/Generated.lean': lean.encode()}
    outputs.update({ROOT / ('verification/search-entry/' + name + '.ts.txt'): data
        for name, (_, _, _, _, data) in selected.items()})
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for path, data in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        elif not path.exists() or path.read_bytes() != data:
            raise SystemExit(f'Stale or changed source artifact: {path.relative_to(ROOT)}')
    print('Pinned collector87, row72, typed selection73 and router ALL initializer9 checked.')


if __name__ == '__main__':
    main()
