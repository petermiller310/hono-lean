#!/usr/bin/env python3
"""Bind actual cache declaration plus exported-arrow setup without claiming module adequacy."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT=Path(__file__).resolve().parents[2]
REVISION='5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE='src/utils/url.ts'
def git(checkout,*args):return subprocess.check_output(['git','-C',str(checkout),*args])
def artifacts(checkout):
    if git(checkout,'rev-parse','HEAD').decode().strip()!=REVISION:raise ValueError('Expected exact pinned revision')
    if git(checkout,'status','--porcelain','--untracked-files=all').strip():raise ValueError('Expected clean checkout; no reset is performed')
    checked=0
    for entry in filter(None,git(checkout,'ls-tree','-rz',REVISION,'--','src','package.json').split(b'\0')):
        info,path=entry.split(b'\t',1);data=(checkout/path.decode()).read_bytes()
        if hashlib.sha1(b'blob '+str(len(data)).encode()+b'\0'+data).hexdigest()!=info.split()[2].decode():raise ValueError('Pinned blob differs: '+path.decode())
        checked+=1
    if checked!=315:raise ValueError('Expected315 pinned blobs')
    raw=git(checkout,'show',REVISION+':'+SOURCE)
    if(checkout/SOURCE).read_bytes()!=raw:raise ValueError('Working source differs')
    setup=raw[1127:1923]
    if setup!=b''.join(raw.splitlines(keepends=True)[49:79]):raise ValueError('Expected complete original LF setup50–79')
    init=(ROOT/'verification/getpattern-cache/init.ts.txt').read_bytes()
    declaration=(ROOT/'verification/getpattern-body/declaration.ts.txt').read_bytes()
    if setup!=init+declaration:raise ValueError('Expected actual50 followed by entire original exportedarrow')
    # Reused source artifacts remain authoritative and byte checked in their own generators.
    sourceCopy='verification/getpattern-invocation/setup.ts.txt'
    metadata=dict(schemaVersion=1,revision=REVISION,repository='https://github.com/honojs/hono.git',sourcePath=SOURCE,
      sourceGitBlob=git(checkout,'rev-parse',REVISION+':'+SOURCE).decode().strip(),sourceSha256=hashlib.sha256(raw).hexdigest(),checkedPinnedBlobs=checked,
      fragments={'setup':dict(firstLine=50,lastLine=79,startByte=1127,endByteExclusive=1923,sha256=hashlib.sha256(setup).hexdigest(),sourceCopy=sourceCopy)},
      reusedSources={'init':'verification/getpattern-cache/source.json','declaration':'verification/getpattern-body/source.json'},
      sourceBoundary='Actual contiguous796B setup50–79 retains typedcache declaration52B and complete exportedarrow744B, including all actualbodybranches and comments. Remaining url.ts module/top-level dependencies are separate.',
      semanticBoundary='Lexicalcells/environment-reference arrowcreation and argumentbinding/currentlookup/body/callerreturn are new proof obligations; source identity/reassembly alone is not invocation, module, TSfrontend or native adequacy.',
      formalCompleteGetPatternTheorem=None,formalModuleTheorem=None,formalNativeLanguageAdequacyTheorem=None)
    lean='-- Generated by verification/getpattern-invocation/source.py; identity is externally checked.\nimport HonoLean.Upstream.PatternCache.Generated\nimport HonoLean.Upstream.GetPatternBody.Generated\nnamespace HonoLean.Upstream.GetPatternInvocation\n\n'
    lean+='def pinnedSetup : String := '+json.dumps(setup.decode('ascii'))+'\n\n'
    lean+='def pinnedInit : String := HonoLean.Upstream.PatternCache.pinnedInit\n\n'
    lean+='def pinnedDeclaration : String := HonoLean.Upstream.GetPatternBody.pinnedDeclaration\n\n'
    lean+='end HonoLean.Upstream.GetPatternInvocation\n'
    return {ROOT/sourceCopy:setup,ROOT/'verification/getpattern-invocation/source.json':(json.dumps(metadata,indent=2)+'\n').encode(),
            ROOT/'HonoLean/Upstream/GetPatternInvocation/Generated.lean':lean.encode()}
def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--hono',type=Path,required=True);parser.add_argument('--write',action='store_true');args=parser.parse_args()
    for path,data in artifacts(args.hono.resolve()).items():
        if args.write:path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
        elif not path.exists()or path.read_bytes()!=data:raise ValueError('Stale source artifact: '+str(path.relative_to(ROOT)))
    print('Pinned315blobs andactual796Bsetup50–79/init52+arrow744 exact reassembly checked.')
if __name__=='__main__':main()
