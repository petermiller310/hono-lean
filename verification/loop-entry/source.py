#!/usr/bin/env python3
"""Bind actual for-header prefixes, including their opening brace and EOF."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/router/trie-router/node.ts'
WINDOWS = [('outer', 'Outer', 99), ('inner', 'Inner', 104)]


def git(checkout, *args):
    return subprocess.check_output(['git', '-C', str(checkout), *args])


def artifacts(checkout):
    if git(checkout, 'rev-parse', 'HEAD').decode().strip() != REVISION:
        raise ValueError('Expected exact pinned Hono revision')
    if git(checkout, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('Expected clean pinned checkout; no reset is performed')
    raw = git(checkout, 'show', REVISION + ':' + SOURCE)
    if (checkout / SOURCE).read_bytes() != raw:
        raise ValueError('Working source bytes differ from pinned Git blob')
    lines = raw.splitlines(keepends=True)
    fragments = {}
    outputs = {}
    lean = ('-- Generated by verification/loop-entry/source.py; source identity is externally checked.\n'
            'namespace HonoLean.Upstream.NodeLoopEntry\n\n')
    for name, lean_name, line in WINDOWS:
        start = sum(map(len, lines[:line-1]))
        end = sum(map(len, lines[:line]))
        fragment = raw[start:end]
        fragments[name] = dict(firstLine=line, lastLine=line, startByte=start,
            endByteExclusive=end, sha256=hashlib.sha256(fragment).hexdigest(),
            whitespacePolicy='Exact indentation and trailing LF retained; EOF immediately follows the actual opening brace line. No body is appended.')
        outputs[ROOT/f'verification/loop-entry/{name}.ts.txt'] = fragment
        lean += f'def pinned{lean_name}Source : String := ' + json.dumps(fragment.decode('ascii')) + '\n\n'
    lean += 'end HonoLean.Upstream.NodeLoopEntry\n'
    metadata = dict(schemaVersion=1, revision=REVISION,
        repository='https://github.com/honojs/hono.git', sourcePath=SOURCE,
        sourceGitBlob=git(checkout, 'rev-parse', REVISION + ':' + SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(raw).hexdigest(), fragments=fragments,
        sourceSubset='Actual for(let initialization; numeric guard; named postincrement) prefixes, parsed through the real opening brace and EOF.',
        controlFlowBoundary='Header initialization/test/increment operations compose with selected actual startup and body-prefix declarations. No fake body, full for-body interpreter, loop completion, remaining branches or whole-search reachability theorem is supplied.',
        snapshotBoundary='Outer len and inner len2 are saved numeric bounds. Later reads require current array/binding frames; a true guard alone does not imply a mutated array still contains that index.',
        formalCompleteSearchTheorem=None, formalCompleteLoopBodyTheorem=None)
    outputs[ROOT/'verification/loop-entry/source.json'] = (json.dumps(metadata, indent=2)+'\n').encode()
    outputs[ROOT/'HonoLean/Upstream/NodeLoopEntry/Generated.lean'] = lean.encode()
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for path, data in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        elif not path.exists() or path.read_bytes() != data:
            raise SystemExit(f'Stale or changed source artifact: {path.relative_to(ROOT)}')
    print('Pinned actual for-header prefixes99/104 through opening brace and EOF checked.')


if __name__ == '__main__':
    main()
