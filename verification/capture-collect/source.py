#!/usr/bin/env python3
"""Bind the original capture guard and its actual five-argument collector call."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/router/trie-router/node.ts'
SPANS = {
    'full': (158, 161, 'a928a495ea1adeed88f748fb0b5392ad2e618b80dccea6442f933417039b5dfa'),
    'guard': (158, 160, 'beff10a225df509ff6010efcaa6271d564693b14a5f1d683d90937170d7c023b'),
    'call': (161, 161, '115f685d4dd5938511c0b39512cb50763ed98d42a49413a97b5d959f507cb07e'),
}


def git(checkout, *args):
    return subprocess.check_output(['git', '-C', str(checkout), *args])


def artifacts(checkout):
    if git(checkout, 'rev-parse', 'HEAD').decode().strip() != REVISION:
        raise ValueError('Expected exact pinned Hono revision')
    if git(checkout, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('Expected clean checkout; no reset is performed')
    raw = git(checkout, 'show', REVISION + ':' + SOURCE)
    if (checkout / SOURCE).read_bytes() != raw:
        raise ValueError('Working source differs from pinned Git bytes')
    lines = raw.splitlines(keepends=True)
    fragments, contents = {}, {}
    for name, (first, last, expected) in SPANS.items():
        start, end = sum(map(len, lines[:first-1])), sum(map(len, lines[:last]))
        source = raw[start:end]
        digest = hashlib.sha256(source).hexdigest()
        if digest != expected:
            raise ValueError('Expected original pinned ' + name + ' fragment')
        copy = 'verification/capture-collect/' + name + '.ts.txt'
        fragments[name] = dict(firstLine=first, lastLine=last, startByte=start,
            endByteExclusive=end, sha256=digest, sourceCopy=copy)
        contents[ROOT / copy] = source
    assert contents[ROOT / fragments['full']['sourceCopy']] == (
        contents[ROOT / fragments['guard']['sourceCopy']] + contents[ROOT / fragments['call']['sourceCopy']])
    metadata = dict(schemaVersion=1, revision=REVISION, repository='https://github.com/honojs/hono.git',
        sourcePath=SOURCE, sourceGitBlob=git(checkout, 'rev-parse', REVISION + ':' + SOURCE).decode().strip(),
        sourceSha256=hashlib.sha256(raw).hexdigest(), fragments=fragments,
        languageReference='ECMA-262, 16th edition (2025)',
        sourceBoundary='Original complete lines158-161: own guard and call. The fourth argument is node.#params; fifth is params. Source123 initializer is linked separately; surrounding if(m), actual regex production and search traversal remain open.',
        semanticBoundary='Conditional ordinary-data descriptor/private-method model; source-produced maps feed actual helper body. Independent initial record/row/read/capacity facts; repeated handler references remain live aliases. No full-router or native-language adequacy theorem.',
        formalCompleteSearchTheorem=None, formalNativeLanguageAdequacyTheorem=None)
    contents[ROOT / 'verification/capture-collect/source.json'] = (json.dumps(metadata, indent=2) + '\n').encode()
    lean = '-- Generated by verification/capture-collect/source.py; identity is externally checked.\nnamespace HonoLean.Upstream.NodeCaptureCollect\n\n'
    for name in ['full', 'guard', 'call']:
        constant = {'full': 'pinnedSource', 'guard': 'pinnedGuard', 'call': 'pinnedCall'}[name]
        lean += 'def ' + constant + ' : String := ' + json.dumps(contents[ROOT / fragments[name]['sourceCopy']].decode('ascii')) + '\n\n'
    lean += 'end HonoLean.Upstream.NodeCaptureCollect\n'
    contents[ROOT / 'HonoLean/Upstream/NodeCaptureCollect/Generated.lean'] = lean.encode()
    return contents


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for path, contents in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(contents)
        elif not path.exists() or path.read_bytes() != contents:
            raise SystemExit(f'Stale or changed artifact: {path.relative_to(ROOT)}')
    print('Pinned188B guard+collector,102B guard and actual86B161 call checked.')


if __name__ == '__main__':
    main()
