#!/usr/bin/env python3
"""Bind Node's selected private data fields and method installation plan.

The five data fields and one private method are parsed separately, with source-order
private identities and method-before-field installation. Public methods and the
containing full class remain provenance, not a complete class translation.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '5ca49b0720755c585c9a9835f0a479ceea36fb52'
SOURCE = 'src/router/trie-router/node.ts'


def git(checkout, *arguments):
    return subprocess.check_output(['git', '-C', str(checkout), *arguments])


def span(contents, first, last):
    lines = contents.splitlines(keepends=True)
    if len(lines) < last:
        raise ValueError('Pinned source window is outside source')
    start, end = sum(map(len, lines[:first-1])), sum(map(len, lines[:last]))
    return start, end, contents[start:end]


def artifacts(checkout):
    actual = git(checkout, 'rev-parse', 'HEAD').decode().strip()
    if actual != REVISION:
        raise ValueError(f'Expected pinned revision {REVISION}, got {actual}')
    if git(checkout, 'status', '--porcelain', '--untracked-files=all').strip():
        raise ValueError('Expected clean pinned Hono checkout; no reset is performed')
    contents = git(checkout, 'show', REVISION + ':' + SOURCE)
    if (checkout/SOURCE).read_bytes() != contents:
        raise ValueError('Working source bytes differ from pinned Git blob')
    selected = {name: (first, last, *span(contents, first, last))
                for name, first, last in [('preamble', 17, 18), ('fields', 21, 26), ('method', 64, 84)]}
    fragments = {}
    for name, (first, last, start, end, data) in selected.items():
        fragments[name] = dict(sourcePath=SOURCE, firstLine=first, lastLine=last,
            startByte=start, endByteExclusive=end, sha256=hashlib.sha256(data).hexdigest(),
            whitespacePolicy='Exact source indentation, blank lines and trailing LF retained')
    first, last = 20, len(contents.splitlines())
    start, end, context = span(contents, first, last)
    metadata = dict(schemaVersion=1, repository='https://github.com/honojs/hono.git',
        revision=REVISION, sourcePath=SOURCE,
        sourceSha256=hashlib.sha256(contents).hexdigest(),
        sourceGitBlob=git(checkout, 'rev-parse', REVISION + ':' + SOURCE).decode().strip(),
        fragments=fragments,
        containingClass=dict(firstLine=first, lastLine=last, startByte=start, endByteExclusive=end,
            sha256=hashlib.sha256(context).hexdigest(), source=context.decode('ascii'),
            verificationStatus='Provenance only; selected private data fields, private method and preamble are parsed separately. Public insert/search, full class evaluation, prototype/default constructor and module linking remain open.'),
        privateNames=['methods', 'children', 'patterns', 'pattern', 'params', 'pushHandlerSets'],
        privateInstallationOrder='The private method read handle is installed before all five ordered data fields, despite appearing after them in source.',
        sourceSubset='Retained private data/method type metadata; shared lexical identities from selected declarations; parsed source method closure appended to a threaded disjoint method table; method-before-field initialization; selected top-level call connection.',
        initializationBoundary='Combined private name reservations and source-bound method closure/read handles are derived. Supplied prototype/helper/import/captured-value context, public methods, native method kinds/read-only enforcement, complete class/default-constructor/newTarget/module live cells and native adequacy remain separate.',
        formalCompleteClassTheorem=None, formalNativeModuleLinkingTheorem=None)
    lean = ('-- Generated by verification/class-installation/source.py; source identity is externally checked.\n'
            'import HonoLean.Upstream.SourceSubset.Syntax\n\n'
            'namespace HonoLean.Upstream.NodeClass\n\n')
    for name, (_, _, _, _, data) in selected.items():
        lean += 'def pinned' + name.title() + 'Source : String := ' + json.dumps(data.decode('ascii')) + '\n\n'
    lean += 'end HonoLean.Upstream.NodeClass\n'
    outputs = {ROOT/'verification/class-installation/source.json': (json.dumps(metadata, indent=2)+'\n').encode(),
               ROOT/'HonoLean/Upstream/NodeClass/Generated.lean': lean.encode()}
    outputs.update({ROOT/('verification/class-installation/'+name+'.ts.txt'): data
                    for name, (_, _, _, _, data) in selected.items()})
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hono', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for path, data in artifacts(args.hono).items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        elif not path.exists() or path.read_bytes() != data:
            raise SystemExit(f'Stale or changed source artifact: {path.relative_to(ROOT)}')
    print('Pinned preamble17–18, fields21–26, private method64–84 and embeddings checked.')


if __name__ == '__main__':
    main()
